import { useState, useEffect } from "react";
import { useNavigate, useSearchParams } from "react-router-dom";
import { motion, AnimatePresence } from "framer-motion";
import { ChevronLeft, ChevronRight, Check, Loader2 } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Progress } from "@/components/ui/progress";
import { cn } from "@/lib/utils";
import {
  usePlayerCharacterIdentity,
  useCreateCharacterIdentity,
  useUpdateCharacterIdentity,
  useCompleteOnboarding,
} from "@/hooks/useCharacterIdentity";
import { useCreateReputation } from "@/hooks/useReputation";
import { useCharacterOrigins, usePersonalityTraits } from "@/hooks/useCharacterIdentity";
import { getCombinedReputationModifiers } from "@/lib/api/roleplaying";
import { supabase } from "@/integrations/supabase/client";
import { useOptionalGameData } from "@/hooks/useGameData";
import { useActiveProfile } from "@/hooks/useActiveProfile";

import { WelcomeStep } from "./steps/WelcomeStep";
import { GenderStep } from "./steps/GenderStep";
import { AppearanceStep } from "./steps/AppearanceStep";
import { OriginStep } from "./steps/OriginStep";
import { TraitsStep } from "./steps/TraitsStep";
import { MusicIdentityStep } from "./steps/MusicIdentityStep";
import { CareerPathStep } from "./steps/CareerPathStep";
import { StartingCityStep } from "./steps/StartingCityStep";
import { BackstoryStep } from "./steps/BackstoryStep";

const STEPS = [
  { id: 1, title: "Welcome", description: "What should the world call you?" },
  { id: 2, title: "Gender", description: "Who are you?" },
  { id: 3, title: "Appearance", description: "Create your look" },
  { id: 4, title: "Origin", description: "Where did your journey begin?" },
  { id: 5, title: "Personality", description: "What defines you?" },
  { id: 6, title: "Musical Identity", description: "Your sound" },
  { id: 7, title: "Career Path", description: "How do you want to start?" },
  { id: 8, title: "Starting City", description: "Choose your home base" },
  { id: 9, title: "Your Story", description: "Review your backstory" },
];

export interface OnboardingData {
  displayName: string;
  artistName: string;
  gender: string;
  originId: string | null;
  traitIds: string[];
  musicalStyle: string;
  careerGoal: string;
  startingCityId: string | null;
  backstoryText: string;
}

export const OnboardingWizard = () => {
  const navigate = useNavigate();
  const [searchParams] = useSearchParams();
  const [currentStep, setCurrentStep] = useState(1);
  const [isTransitioning, setIsTransitioning] = useState(false);
  const gameData = useOptionalGameData();
  const { profile: activeProfile, profileId: activeProfileId } = useActiveProfile();
  const requestedProfileId = searchParams.get("profileId");
  const profileId = requestedProfileId ?? activeProfileId ?? gameData?.profile?.id ?? null;
  const profile =
    gameData?.profile?.id === profileId
      ? gameData.profile
      : activeProfile?.id === profileId
        ? activeProfile
        : null;

  const [data, setData] = useState<OnboardingData>({
    displayName: "",
    artistName: "",
    gender: "",
    originId: null,
    traitIds: [],
    musicalStyle: "",
    careerGoal: "solo",
    startingCityId: null,
    backstoryText: "",
  });
  const [profileHydrated, setProfileHydrated] = useState(false);

  const { data: identity } = usePlayerCharacterIdentity(profileId ?? undefined);
  const { data: origins = [] } = useCharacterOrigins();
  const { data: traits = [] } = usePersonalityTraits();

  const createIdentity = useCreateCharacterIdentity(profileId ?? undefined);
  const updateIdentity = useUpdateCharacterIdentity(profileId ?? undefined);
  const createReputation = useCreateReputation(profileId ?? undefined);
  const completeOnboarding = useCompleteOnboarding(profileId ?? undefined);

  useEffect(() => {
    if (profileId && identity === null && !createIdentity.isPending) {
      createIdentity.mutate();
    }
  }, [profileId, identity, createIdentity]);

  useEffect(() => {
    if (profileHydrated || !profile) return;
    const looksAutoGenerated = (u?: string | null) =>
      !u || /^(player|child-of)-/i.test(u);
    setData((prev) => ({
      ...prev,
      displayName: prev.displayName || profile.display_name || "",
      artistName:
        prev.artistName ||
        (looksAutoGenerated(profile.username) ? "" : profile.username || ""),
      backstoryText: prev.backstoryText || (profile as any).bio || "",
    }));
    setProfileHydrated(true);
  }, [profile, profileHydrated]);

  useEffect(() => {
    if (identity && identity.onboarding_step > 0) {
      setCurrentStep(Math.min(identity.onboarding_step + 1, STEPS.length));
      setData((prev) => ({
        ...prev,
        originId: identity.origin_id,
        traitIds: identity.trait_ids ?? [],
        musicalStyle: identity.musical_style ?? "",
        careerGoal: identity.career_goal ?? "solo",
        startingCityId: identity.starting_city_id,
        backstoryText: prev.backstoryText || identity.backstory_text || "",
      }));
    }
  }, [identity]);

  const updateData = (updates: Partial<OnboardingData>) => {
    setData((prev) => ({ ...prev, ...updates }));
  };

  const progress = (currentStep / STEPS.length) * 100;

  const canProceed = (): boolean => {
    switch (currentStep) {
      case 1:
        return data.displayName.trim().length >= 2;
      case 2:
        return data.gender.length > 0;
      case 3:
        return true;
      case 4:
        return data.originId !== null;
      case 5:
        return data.traitIds.length >= 2 && data.traitIds.length <= 3;
      case 6:
        return data.musicalStyle.trim().length > 0;
      case 7:
        return data.careerGoal.length > 0;
      case 8:
        return data.startingCityId !== null;
      case 9:
        return true;
      default:
        return false;
    }
  };

  const saveProgress = async () => {
    if (!profileId) throw new Error("No profile ID available for onboarding");
    if (!identity) return;

    await updateIdentity.mutateAsync({
      origin_id: data.originId,
      trait_ids: data.traitIds,
      musical_style: data.musicalStyle,
      career_goal: data.careerGoal,
      starting_city_id: data.startingCityId,
      backstory_text: data.backstoryText,
      onboarding_step: currentStep,
    });
  };

  const handleNext = async () => {
    if (!canProceed() || isTransitioning) return;

    setIsTransitioning(true);

    try {
      await saveProgress();
      if (currentStep < STEPS.length) {
        setCurrentStep((prev) => prev + 1);
        window.scrollTo({ top: 0, behavior: "smooth" });
      }
    } finally {
      setIsTransitioning(false);
    }
  };

  const handleBack = () => {
    if (currentStep > 1 && !isTransitioning) {
      setCurrentStep((prev) => prev - 1);
      window.scrollTo({ top: 0, behavior: "smooth" });
    }
  };

  const handleComplete = async () => {
    if (isTransitioning) return;

    setIsTransitioning(true);

    try {
      if (!profileId) {
        throw new Error("No profile ID available for onboarding completion");
      }

      await saveProgress();

      const profileUpdates: Record<string, any> = {
        display_name: data.displayName.trim(),
        gender: data.gender,
      };
      if (data.artistName.trim()) {
        profileUpdates.username = data.artistName.trim();
      }
      if (data.backstoryText.trim()) {
        profileUpdates.bio = data.backstoryText.trim();
      }

      const { error: profileUpdateError } = await supabase
        .from("profiles")
        .update(profileUpdates as any)
        .eq("id", profileId);

      if (profileUpdateError) {
        throw new Error(`Failed to save profile details: ${profileUpdateError.message}`);
      }

      const { error: walletError } = await supabase
        .from("player_xp_wallet")
        .upsert({
          profile_id: profileId,
          xp_balance: 1000,
          lifetime_xp: 1000,
          attribute_points_balance: 300,
          attribute_points_lifetime: 300,
        }, { onConflict: "profile_id" });

      if (walletError) {
        throw new Error(`Failed to create starter wallet: ${walletError.message}`);
      }

      const selectedOrigin = origins.find((o) => o.id === data.originId) ?? null;
      const selectedTraits = traits.filter((t) => data.traitIds.includes(t.id));
      const modifiers = getCombinedReputationModifiers(selectedOrigin, selectedTraits);

      await createReputation.mutateAsync(modifiers);
      await completeOnboarding.mutateAsync();

      navigate("/home");
    } finally {
      setIsTransitioning(false);
    }
  };

  const renderStep = () => {
    switch (currentStep) {
      case 1:
        return <WelcomeStep data={data} updateData={updateData} />;
      case 2:
        return <GenderStep data={data} updateData={updateData} />;
      case 3:
        return <AppearanceStep />;
      case 4:
        return <OriginStep data={data} updateData={updateData} />;
      case 5:
        return <TraitsStep data={data} updateData={updateData} />;
      case 6:
        return <MusicIdentityStep data={data} updateData={updateData} />;
      case 7:
        return <CareerPathStep data={data} updateData={updateData} />;
      case 8:
        return <StartingCityStep data={data} updateData={updateData} />;
      case 9:
        return (
          <BackstoryStep
            data={data}
            updateData={updateData}
            origins={origins}
            traits={traits}
          />
        );
      default:
        return null;
    }
  };

  const isLastStep = currentStep === STEPS.length;
  const isSaving =
    updateIdentity.isPending ||
    createReputation.isPending ||
    completeOnboarding.isPending ||
    isTransitioning;

  const primaryAction = isLastStep ? (
    <Button
      onClick={handleComplete}
      disabled={!canProceed() || isSaving || !profileId}
      className="min-w-[130px]"
      size="sm"
    >
      {isSaving ? (
        <Loader2 className="mr-2 h-4 w-4 animate-spin" />
      ) : (
        <Check className="mr-2 h-4 w-4" />
      )}
      Begin Journey
    </Button>
  ) : (
    <Button
      onClick={handleNext}
      disabled={!canProceed() || isTransitioning || !profileId}
      className="min-w-[90px]"
      size="sm"
    >
      {isTransitioning ? (
        <Loader2 className="mr-2 h-4 w-4 animate-spin" />
      ) : (
        <>
          Next
          <ChevronRight className="ml-1 h-4 w-4" />
        </>
      )}
    </Button>
  );

  return (
    <div className="flex min-h-screen flex-col">
      <header className="sticky top-0 z-20 border-b border-border/50 bg-background/95 backdrop-blur-sm">
        <div className="container mx-auto px-4 py-3 sm:py-4">
          <div className="mb-3 flex items-center justify-between gap-3">
            <div className="min-w-0">
              <h1 className="truncate text-lg font-semibold text-foreground">
                {STEPS[currentStep - 1].title}
              </h1>
              <p className="hidden text-sm text-muted-foreground sm:block">
                {STEPS[currentStep - 1].description}
              </p>
            </div>
            <div className="flex shrink-0 items-center gap-3">
              <div className="hidden text-sm text-muted-foreground sm:block">
                Step {currentStep} of {STEPS.length}
              </div>
              {primaryAction}
            </div>
          </div>
          <div className="mb-2 text-xs text-muted-foreground sm:hidden">
            Step {currentStep} of {STEPS.length}
          </div>
          <Progress value={progress} className="h-1.5" />
        </div>
      </header>

      <main className="container mx-auto flex-1 px-4 py-6">
        <AnimatePresence mode="wait">
          <motion.div
            key={currentStep}
            initial={{ opacity: 0, x: 20 }}
            animate={{ opacity: 1, x: 0 }}
            exit={{ opacity: 0, x: -20 }}
            transition={{ duration: 0.2 }}
            className="mx-auto max-w-3xl"
          >
            {renderStep()}
          </motion.div>
        </AnimatePresence>
      </main>

      <footer className="border-t border-border/50 bg-background/80 backdrop-blur-sm">
        <div className="container mx-auto flex items-center justify-between px-4 py-4">
          <Button
            variant="ghost"
            onClick={handleBack}
            disabled={currentStep === 1 || isTransitioning}
            className={cn(currentStep === 1 && "invisible")}
          >
            <ChevronLeft className="mr-1 h-4 w-4" />
            Back
          </Button>

          <div className="hidden items-center gap-1.5 md:flex">
            {STEPS.map((step) => (
              <div
                key={step.id}
                className={cn(
                  "h-2 w-2 rounded-full transition-colors",
                  step.id === currentStep
                    ? "bg-primary"
                    : step.id < currentStep
                      ? "bg-primary/50"
                      : "bg-muted"
                )}
              />
            ))}
          </div>

          <div className="w-20" aria-hidden="true" />
        </div>
      </footer>
    </div>
  );
};
