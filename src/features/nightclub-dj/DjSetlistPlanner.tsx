import { useMemo, useState } from "react";
import { useQuery, useQueryClient } from "@tanstack/react-query";
import { ArrowDown, ArrowUp, ListMusic, Plus, Save, Trash2 } from "lucide-react";
import { toast } from "sonner";
import { supabase } from "@/integrations/supabase/client";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { Input } from "@/components/ui/input";
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from "@/components/ui/select";
import type { DjAudioTrack } from "./library";
import { formatDjTime } from "./mixerMath";
import {
  DJ_SETLIST_MAX_TRACKS, djSetlistIsValid, djSetlistSummary, djSetlistTrackKey,
  moveDjSetlistItem, toDjSetlistItem, type DjSavedSet, type DjSetlistItem,
} from "./setlists";

type Props = {
  profileId: string | null;
  tracks: DjAudioTrack[];
  onRehearse: (first: string, second: string) => void;
  onLoadTrack: (trackId: string, deck: "A" | "B") => void;
};

function djSetsTable() {
  // The freshly applied table is not yet in autogenerated Supabase TypeScript types.
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  return (supabase as any).from("dj_setlists");
}

/** Rehearsal drafts only. The future nightclub booking service must check rights again. */
export function DjSetlistPlanner({ profileId, tracks, onRehearse, onLoadTrack }: Props) {
  const queryClient = useQueryClient();
  const [activeId, setActiveId] = useState("");
  const [name, setName] = useState("New DJ set");
  const [items, setItems] = useState<DjSetlistItem[]>([]);
  const [addId, setAddId] = useState("");
  const [version, setVersion] = useState(0);
  const [saving, setSaving] = useState(false);
  const [dirty, setDirty] = useState(false);

  const { data: saved = [], isLoading, isError } = useQuery<DjSavedSet[]>({
    queryKey: ["dj-saved-setlists", profileId],
    enabled: Boolean(profileId),
    queryFn: async () => {
      const { data, error } = await djSetsTable()
        .select("id,name,user_id,profile_id,items,version,created_at,updated_at")
        .eq("profile_id", profileId).order("updated_at", { ascending: false }).limit(50);
      if (error) throw error;
      return (data ?? []) as DjSavedSet[];
    },
  });

  const availableById = useMemo(() => new Map(tracks.map((track) => [track.id, track])), [tracks]);
  const summary = useMemo(() => djSetlistSummary(items, tracks), [items, tracks]);
  const canSave = Boolean(profileId) && !saving && name.trim().length >= 1
    && name.trim().length <= 80 && djSetlistIsValid(items, tracks);

  const loadSaved = (id: string) => {
    if (dirty && !window.confirm("Discard unsaved DJ set changes?")) return;
    if (!id) {
      setActiveId(""); setVersion(0); setItems([]); setName("New DJ set"); setDirty(false);
      return;
    }
    const row = saved.find((entry) => entry.id === id);
    if (!row) return;
    setActiveId(row.id);
    setVersion(row.version);
    setName(row.name);
    setItems(Array.isArray(row.items) ? [...row.items] : []);
    setDirty(false);
  };

  const appendTrack = () => {
    const track = availableById.get(addId);
    if (!track || items.length >= DJ_SETLIST_MAX_TRACKS) return;
    setItems((previous) => [...previous, toDjSetlistItem(track)]);
    setDirty(true);
  };

  const save = async () => {
    if (!canSave || !profileId) return;
    setSaving(true);
    try {
      const { data: auth, error: authError } = await supabase.auth.getUser();
      if (authError || !auth.user) throw authError || new Error("Sign in to save a DJ set");
      const payload = { name: name.trim(), items };
      // Database RLS and the validation trigger enforce character and audio rights.
      let operation;
      if (activeId) {
        operation = djSetsTable()
          .update(payload).eq("id", activeId).eq("profile_id", profileId)
          .eq("version", version).select("id,version").maybeSingle();
      } else {
        operation = djSetsTable()
          .insert({ ...payload, user_id: auth.user.id, profile_id: profileId })
          .select("id,version").single();
      }
      const { data, error } = await operation;
      if (error) throw error;
      if (!data) throw new Error("This set was changed in another session. Reload your saved set before retrying.");
      setActiveId(data.id);
      setVersion(data.version);
      setDirty(false);
      await queryClient.invalidateQueries({ queryKey: ["dj-saved-setlists", profileId] });
      toast.success("DJ set saved. You can return and rehearse it later.");
    } catch (error) {
      toast.error(error instanceof Error ? error.message : "Could not save DJ set");
    } finally {
      setSaving(false);
    }
  };

  const remove = async () => {
    if (!activeId || !profileId || saving) return;
    if (!window.confirm("Delete this saved DJ set? This will not delete any songs.")) return;
    setSaving(true);
    try {
      const { data, error } = await djSetsTable()
        .delete().eq("id", activeId).eq("profile_id", profileId)
        .eq("version", version).select("id").maybeSingle();
      if (error) throw error;
      if (!data) throw new Error("This set changed in another session. Reload before deleting.");
      setActiveId(""); setVersion(0); setItems([]); setName("New DJ set"); setDirty(false);
      await queryClient.invalidateQueries({ queryKey: ["dj-saved-setlists", profileId] });
      toast.success("Saved DJ set deleted.");
    } catch (error) {
      toast.error(error instanceof Error ? error.message : "Unable to delete DJ set");
    } finally { setSaving(false); }
  };

  const rehearse = () => {
    if (summary.missing > 0 || items.length === 0) {
      toast.error("Replace unavailable songs before loading this set into the decks.");
      return;
    }
    onRehearse(djSetlistTrackKey(items[0]),
      djSetlistTrackKey(items[1] ?? items[0]));
    toast.success("The first two setlist tracks are ready in the decks.");
  };

  return (
    <Card data-testid="dj-setlist-planner">
      <CardHeader className="pb-2">
        <CardTitle className="flex items-center justify-between gap-2 text-base">
          <span className="flex gap-2 items-center"><ListMusic className="h-4 w-4" /> Prepare a DJ set</span>
          <Badge variant="outline">Practice · No rewards</Badge>
        </CardTitle>
      </CardHeader>
      <CardContent className="space-y-4">
        <p className="text-xs text-muted-foreground">
          Build and save your track order, then load the first two songs into the mixer.
          A future booked gig will validate rights and audio again.
        </p>
        <div className="flex flex-wrap items-end gap-2">
          <div className="flex-1 min-w-48 space-y-1">
            <label htmlFor="dj-saved-set" className="text-xs">Saved DJ sets</label>
            <Select value={activeId || "new"} onValueChange={(value) => loadSaved(value === "new" ? "" : value)}>
              <SelectTrigger id="dj-saved-set" aria-label="Choose saved DJ set">
                <SelectValue placeholder="Choose a saved set..." />
              </SelectTrigger>
              <SelectContent>
                <SelectItem value="new">New DJ set</SelectItem>
                {saved.map((row) => <SelectItem key={row.id} value={row.id}>{row.name}</SelectItem>)}
              </SelectContent>
            </Select>
          </div>
          <Button type="button" variant="outline" onClick={() => loadSaved("")} disabled={saving}>
            <Plus className="h-4 w-4 mr-1" /> New
          </Button>
        </div>
        {isLoading && <p className="text-xs text-muted-foreground">Loading saved sets...</p>}
        {isError && <p className="text-xs text-destructive" role="alert">Could not load saved DJ sets. Check your connection.</p>}
        <div className="space-y-1">
          <label htmlFor="dj-set-name" className="text-xs">Set name</label>
          <Input id="dj-set-name" value={name} maxLength={80}
            onChange={(event) => { setName(event.target.value); setDirty(true); }}
            placeholder="Friday Night House" />
        </div>
        <div className="flex flex-wrap gap-2 items-end">
          <div className="flex-1 min-w-52 space-y-1">
            <label htmlFor="dj-add-track" className="text-xs">Add a playable track</label>
            <Select value={addId || undefined} onValueChange={setAddId}>
              <SelectTrigger id="dj-add-track" aria-label="Choose a track to add to DJ set">
                <SelectValue placeholder="Choose from my DJ library..." />
              </SelectTrigger>
              <SelectContent className="max-h-72">
                {tracks.map((track) => <SelectItem key={track.id} value={track.id}>
                  {track.title} · {track.artist}
                </SelectItem>)}
              </SelectContent>
            </Select>
          </div>
          <Button type="button" variant="outline" disabled={!addId || items.length >= DJ_SETLIST_MAX_TRACKS}
            onClick={appendTrack}><Plus className="h-4 w-4 mr-1" /> Add</Button>
        </div>
        <div className="space-y-2">
          {items.length === 0 && <p className="text-sm text-muted-foreground rounded-md border border-dashed p-4">
            No songs added yet. Add at least one playable track to save a rehearsal set.
          </p>}
          {items.map((item, index) => {
            const track = availableById.get(djSetlistTrackKey(item));
            return (
              <div key={`${djSetlistTrackKey(item)}:${index}`}
                className="flex items-center gap-2 rounded-md border p-2">
                <span className="text-xs text-muted-foreground w-5 text-center">{index + 1}</span>
                <div className="flex-1 min-w-0">
                  <p className="text-sm font-medium truncate">{track?.title ?? "Unavailable track"}</p>
                  <p className="text-xs text-muted-foreground truncate">
                    {track ? `${track.artist} · ${track.genre} · ${track.durationSeconds ? formatDjTime(track.durationSeconds) : "Duration unknown"}`
                      : "Removed, unpublished or sharing withdrawn — replace before saving"}
                  </p>
                </div>
                <Button type="button" size="sm" variant="outline" disabled={!track}
                  aria-label={`Load ${track?.title ?? "unavailable song"} into deck A`}
                  onClick={() => onLoadTrack(djSetlistTrackKey(item), "A")}>A</Button>
                <Button type="button" size="sm" variant="outline" disabled={!track}
                  aria-label={`Load ${track?.title ?? "unavailable song"} into deck B`}
                  onClick={() => onLoadTrack(djSetlistTrackKey(item), "B")}>B</Button>
                <Button type="button" size="icon" variant="ghost" aria-label={`Move song ${index + 1} up`}
                  disabled={index === 0} onClick={() => { setItems(moveDjSetlistItem(items, index, index - 1)); setDirty(true); }}>
                  <ArrowUp className="h-4 w-4" />
                </Button>
                <Button type="button" size="icon" variant="ghost" aria-label={`Move song ${index + 1} down`}
                  disabled={index === items.length - 1} onClick={() => { setItems(moveDjSetlistItem(items, index, index + 1)); setDirty(true); }}>
                  <ArrowDown className="h-4 w-4" />
                </Button>
                <Button type="button" size="icon" variant="ghost" aria-label={`Remove song ${index + 1}`}
                  onClick={() => { setItems(items.filter((_, i) => i !== index)); setDirty(true); }}>
                  <Trash2 className="h-4 w-4" />
                </Button>
              </div>
            );
          })}
        </div>
        <div className="flex flex-wrap items-center gap-2 justify-between">
          <p className="text-xs text-muted-foreground">
            {summary.count}/{DJ_SETLIST_MAX_TRACKS} tracks · At least {formatDjTime(summary.durationSeconds)} audio
            {summary.unknownDuration > 0 ? ` · ${summary.unknownDuration} durations unknown` : ""}
            {summary.missing > 0 ? ` · ${summary.missing} unavailable` : ""}
            {dirty ? " · Unsaved changes" : ""}
          </p>
          <div className="flex flex-wrap gap-2">
            <Button type="button" variant="outline" disabled={items.length === 0 || summary.missing > 0}
              onClick={rehearse}>Load first two decks</Button>
            {activeId && <Button type="button" variant="outline" disabled={saving} onClick={remove}>
              <Trash2 className="h-4 w-4 mr-1" /> Delete
            </Button>}
            <Button type="button" disabled={!canSave} onClick={save}>
              <Save className="h-4 w-4 mr-1" /> {saving ? "Saving..." : activeId ? "Save changes" : "Save set"}
            </Button>
          </div>
        </div>
      </CardContent>
    </Card>
  );
}
