import { useState, type KeyboardEvent } from "react";
import { Link } from "react-router-dom";
import { Button } from "@/components/ui/button";
import { festivalRoutes } from "@/features/festivals/routes";
import { getAnnualPlanCapacityProjection, type FestivalAnnualPlan } from "./model";

type Zone = "stage" | "audience" | "facilities" | "arrival" | "trading";
type PlanningSection = "when" | "festival" | "promotion";

const zoneLayout: { key: Zone; label: string; x: number; y: number; code: string }[] = [
  { key: "stage", label: "Stage production", x: 42, y: 40, code: "01" },
  { key: "audience", label: "Audience capacity", x: 340, y: 40, code: "02" },
  { key: "facilities", label: "Facilities & safety", x: 638, y: 40, code: "03" },
  { key: "arrival", label: "Arrival & travel", x: 192, y: 225, code: "04" },
  { key: "trading", label: "Food & trading", x: 490, y: 225, code: "05" },
];

const activate = (event: KeyboardEvent<SVGGElement>, action: () => void) => {
  if (event.key === "Enter" || event.key === " ") {
    event.preventDefault();
    action();
  }
};

const display = (value: number | null) => value === null ? "Not calculated" : value.toLocaleString("en-GB");

export function FestivalPlanningOverlay({ plan, unsavedChanges, onOpenSection }: {
  plan: FestivalAnnualPlan;
  unsavedChanges: boolean;
  onOpenSection: (section: PlanningSection) => void;
}) {
  const [selected, setSelected] = useState<Zone>("audience");
  const capacity = getAnnualPlanCapacityProjection(plan);
  const licenceBlockers = plan.blockers.filter((item) => item.code.startsWith("festival_licence_"));
  const zoneDetail: Record<Zone, { description: string; action?: PlanningSection }> = {
    stage: {
      description: `The game derives stage production and the running order from the Festival size (${plan.festivalScale ?? "not selected"}) and company upgrades. Individual stage positions are not supplied by this plan.`,
      action: "festival",
    },
    audience: {
      description: `Server-projected usable capacity: ${display(capacity.licensedCapacity)}. Potential capacity: ${display(capacity.potentialCapacity)}.${capacity.capacityRestrictedByLicence ? " The active licence reduces the usable allocation." : ""}`,
      action: "festival",
    },
    facilities: {
      description: "Medical points, security, welfare and supplier requirements are generated by the game. The current annual-plan projection does not provide verified facility counts or positions.",
    },
    arrival: {
      description: `The Festival city is ${plan.city?.name ?? "not chosen"}; travel routes, gate positions and accessible entrances are not published by this planning projection.`,
      action: "when",
    },
    trading: {
      description: `Food, merchandise and other concessions are simulated automatically. Promotion emphasis: ${plan.marketingEmphasis ?? "not chosen"}. Vendor locations and sales are not predicted here.`,
      action: "promotion",
    },
  };

  return (
    <section className="space-y-3 rounded-xl border bg-card p-4" aria-label="Festival owner visual planning overlay">
      <div>
        <h3 className="text-base font-semibold">Visual planning overview</h3>
        <p className="text-xs text-muted-foreground">
          Conceptual SVG layout of the planning areas, not an approved site map, stage placement or walking route. All figures are from the saved edition projection.
        </p>
        {unsavedChanges && <p role="status" className="mt-2 text-sm text-amber-700">You have unsaved Festival choices. Save them to refresh the projected capacity and constraints.</p>}
      </div>
      <svg data-testid="festival-owner-svg-plan" role="group" aria-label="Choose a conceptual planning zone" viewBox="0 0 900 365" className="h-auto w-full rounded-lg border bg-slate-950">
        <rect width="900" height="365" fill="#172b40" />
        <path d="M 45 195 H 850 M 270 195 V 212 M 578 195 V 212" stroke="#64748b" strokeWidth="7" strokeDasharray="18 12" opacity="0.45" />
        {zoneLayout.map(({ key, label, x, y, code }) => {
          const active = selected === key;
          const choose = () => setSelected(key);
          return (
            <g key={key} role="button" tabIndex={0} aria-pressed={active} aria-label={`Inspect ${label} planning zone`}
              onClick={choose} onKeyDown={(event) => activate(event, choose)} className="group cursor-pointer">
              <rect x={x} y={y} width="220" height="115" rx="16" fill={active ? "#0f766e" : "#334155"}
                stroke={active ? "#fef08a" : "#94a3b8"} strokeWidth={active ? 5 : 2}
                className="group-focus-visible:stroke-yellow-200 group-focus-visible:stroke-[5px]" />
              <text x={x + 19} y={y + 33} fill="#a5f3fc" fontSize="23" fontWeight="700">{code}</text>
              <text x={x + 110} y={y + 67} fill="white" textAnchor="middle" fontSize="17" fontWeight="700">{label}</text>
              <text x={x + 110} y={y + 92} fill="#e2e8f0" textAnchor="middle" fontSize="12">{key === "audience" ? `${display(capacity.licensedCapacity)} usable` : "Game-planned area"}</text>
            </g>
          );
        })}
      </svg>
      <div className="flex flex-wrap gap-2" role="group" aria-label="Select an owner planning area">
        {zoneLayout.map(({ key, label }) => (
          <Button key={key} type="button" size="sm" variant={selected === key ? "default" : "outline"}
            aria-pressed={selected === key} onClick={() => setSelected(key)}>{label}</Button>
        ))}
      </div>
      <div className="rounded-lg border p-3" role="status" aria-live="polite">
        <h4 className="font-semibold">{zoneLayout.find((zone) => zone.key === selected)?.label}</h4>
        <p className="mt-1 text-sm text-muted-foreground">{zoneDetail[selected].description}</p>
        {zoneDetail[selected].action && (
          <Button size="sm" variant="outline" className="mt-3" type="button"
            disabled={!plan.canWrite || !plan.editable} onClick={() => onOpenSection(zoneDetail[selected].action!)}>
            Review {zoneLayout.find((zone) => zone.key === selected)?.label.toLowerCase()}
          </Button>
        )}
      </div>
      {licenceBlockers.length > 0 && (
        <div role="alert" className="space-y-2 rounded-lg border border-amber-500/40 bg-amber-500/5 p-3 text-sm">
          <p className="font-semibold">Licence constraint on the current plan</p>
          {licenceBlockers.map((item) => <p key={item.code}>{item.message}</p>)}
          <Button size="sm" variant="outline" asChild><Link to={festivalRoutes.upgrades(plan.festivalCompanyId)}>Review Festival licence</Link></Button>
        </div>
      )}
    </section>
  );
}
