-- Festival V2: private, immutable canonical stage event ledger (review-only).
-- Do not apply in production before matching runtime engine emission and
-- disposable database tests. This does NOT synthesise live performances.
--
-- Trust boundary: public.festival_runtime_evidence is service-only writable.
-- Never ingest legacy festival_performance_sessions or legacy crowd snapshots.
CREATE TABLE IF NOT EXISTS private.festival_edition_stage_events (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  runtime_id uuid NOT NULL REFERENCES public.festival_edition_runtimes(id),
  edition_id uuid NOT NULL REFERENCES public.festival_editions_v2(id),
  stage_id uuid NOT NULL REFERENCES public.festival_site_plan_stages(id),
  schedule_item_id uuid NOT NULL,
  source_evidence_id uuid NOT NULL UNIQUE REFERENCES public.festival_runtime_evidence(id),
  event_status text NOT NULL CHECK (event_status IN ('ready','starting','live','delayed','completed','cancelled')),
  festival_date date NOT NULL,
  observed_at timestamptz NOT NULL,
  recorded_at timestamptz NOT NULL DEFAULT now(),
  schema_version integer NOT NULL DEFAULT 1 CHECK (schema_version = 1)
);
CREATE INDEX IF NOT EXISTS festival_edition_stage_events_lookup
  ON private.festival_edition_stage_events (edition_id,stage_id,festival_date,observed_at DESC);
ALTER TABLE private.festival_edition_stage_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE private.festival_edition_stage_events FORCE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE private.festival_edition_stage_events FROM PUBLIC, anon, authenticated, service_role;

-- There is intentionally NO public RPC, no user-writable endpoint, and no
-- trigger against the visitor page. Only an actual trusted runtime evidence
-- insertion can create a stage event.
CREATE OR REPLACE FUNCTION private.capture_canonical_festival_stage_evidence()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $canonical_event$
DECLARE
  v_runtime public.festival_edition_runtimes%ROWTYPE;
  v_stage_id uuid;
  v_item_id uuid;
  v_date date;
  v_observed_at timestamptz;
  v_timezone text;
  v_status text;
BEGIN
  IF NEW.evidence_type NOT IN
    ('stage_ready','stage_starting','stage_live','stage_delayed','stage_completed','stage_cancelled')
  THEN RETURN NEW; END IF;

  IF jsonb_typeof(NEW.evidence) IS DISTINCT FROM 'object' THEN
    RAISE EXCEPTION 'festival_stage_evidence_invalid';
  END IF;

  -- Status is sourced from the trusted evidence type, never untrusted JSON.
  v_status := substring(NEW.evidence_type FROM 7);
  v_stage_id := (NEW.evidence->>'stageId')::uuid;
  v_item_id := (NEW.evidence->>'scheduleItemId')::uuid;
  v_date := (NEW.evidence->>'festivalDate')::date;
  v_observed_at := (NEW.evidence->>'observedAt')::timestamptz;
  IF v_stage_id IS NULL OR v_item_id IS NULL OR v_date IS NULL OR v_observed_at IS NULL THEN
    RAISE EXCEPTION 'festival_stage_evidence_missing_identity';
  END IF;

  SELECT * INTO v_runtime
  FROM public.festival_edition_runtimes r WHERE r.id=NEW.runtime_id;
  IF NOT FOUND OR v_runtime.state NOT IN ('gates_open','live','paused','closing') THEN
    RAISE EXCEPTION 'festival_stage_runtime_inactive';
  END IF;

  -- Require the stage to belong to the *same* canonical annual edition.
  IF NOT EXISTS (
    SELECT 1 FROM public.festival_site_plan_stages st
    JOIN public.festival_site_plans p ON p.id=st.festival_site_plan_id
    WHERE st.id=v_stage_id AND st.status='ready'
      AND p.festival_edition_id=v_runtime.edition_id
      AND p.festival_company_id=v_runtime.festival_company_id
  ) THEN RAISE EXCEPTION 'festival_stage_wrong_edition'; END IF;

  -- Require the stage+artist item to have been generated by THIS runtime.
  IF NOT EXISTS (
    SELECT 1 FROM jsonb_array_elements(
      coalesce(v_runtime.generated_schedule->'items','[]'::jsonb)
    ) AS item
    WHERE item->>'id'=v_item_id::text
      AND item->>'stageId'=v_stage_id::text
      AND item->>'festivalDate'=v_date::text
  ) THEN RAISE EXCEPTION 'festival_stage_item_not_in_runtime'; END IF;

  SELECT coalesce(nullif(c.timezone,''),'UTC') INTO v_timezone
  FROM public.festival_editions_v2 e
  JOIN public.cities c ON c.id=e.city_id
  WHERE e.id=v_runtime.edition_id
    AND v_date BETWEEN e.starts_on AND e.ends_on;
  IF v_timezone IS NULL OR (v_observed_at AT TIME ZONE v_timezone)::date <> v_date
     OR v_observed_at < NEW.created_at - interval '15 minutes'
     OR v_observed_at > NEW.created_at + interval '1 minute' THEN
    RAISE EXCEPTION 'festival_stage_observation_out_of_day';
  END IF;

  INSERT INTO private.festival_edition_stage_events(
    runtime_id,edition_id,stage_id,schedule_item_id,source_evidence_id,
    event_status,festival_date,observed_at
  ) VALUES (
    NEW.runtime_id,v_runtime.edition_id,v_stage_id,v_item_id,NEW.id,
    v_status,v_date,v_observed_at
  );
  RETURN NEW;
END;
$canonical_event$;

REVOKE ALL ON FUNCTION private.capture_canonical_festival_stage_evidence()
  FROM PUBLIC, anon, authenticated, service_role;

DROP TRIGGER IF EXISTS festival_canonical_stage_evidence_capture
  ON public.festival_runtime_evidence;
CREATE TRIGGER festival_canonical_stage_evidence_capture
AFTER INSERT ON public.festival_runtime_evidence
FOR EACH ROW EXECUTE FUNCTION private.capture_canonical_festival_stage_evidence();
