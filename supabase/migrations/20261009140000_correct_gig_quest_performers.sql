-- Only confirmed performers earn gig quest progress. Band membership at
-- consequence-processing time is not evidence of having played that gig.
create or replace function public.record_completed_gig_skill_quest()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
  if new.status <> 'completed'
     or (tg_op = 'UPDATE' and old.status is not distinct from new.status) then
    return new;
  end if;

  insert into public.skill_quest_events(profile_id, quest_id, source_type, source_id)
  select distinct gp.profile_id, 'first_live_show', 'gig_completed', new.gig_id
  from public.gig_performers gp
  join public.gigs g on g.id = gp.gig_id
  where gp.gig_id = new.gig_id
    and gp.band_id = g.band_id
    and gp.lineup_status = 'performed'
    and gp.performed_at is not null
    and g.status = 'completed'
    and g.result_ready_at is not null
  on conflict (profile_id, quest_id, source_type, source_id) do nothing;

  return new;
end;
$$;
revoke all on function public.record_completed_gig_skill_quest() from public, anon, authenticated;

-- Correct false positives generated by the earlier membership-based trigger.
-- No XP or rewards have been configured, so only quest evidence is affected.
delete from public.skill_quest_events e
where e.quest_id = 'first_live_show'
  and e.source_type = 'gig_completed'
  and not exists (
    select 1
    from public.gig_performers gp
    join public.gigs g on g.id = gp.gig_id
    join public.gig_post_processing p on p.gig_id = g.id
    where gp.gig_id = e.source_id
      and gp.profile_id = e.profile_id
      and gp.band_id = g.band_id
      and gp.lineup_status = 'performed'
      and gp.performed_at is not null
      and g.status = 'completed'
      and g.result_ready_at is not null
      and p.status = 'completed'
  );

-- Backfill from the historical lineup evidence, not current band membership.
insert into public.skill_quest_events(profile_id, quest_id, source_type, source_id)
select distinct gp.profile_id, 'first_live_show', 'gig_completed', g.id
from public.gig_performers gp
join public.gigs g on g.id = gp.gig_id and g.band_id = gp.band_id
join public.gig_post_processing p on p.gig_id = g.id and p.status = 'completed'
where gp.lineup_status = 'performed'
  and gp.performed_at is not null
  and g.status = 'completed'
  and g.result_ready_at is not null
on conflict (profile_id, quest_id, source_type, source_id) do nothing;
