CREATE OR REPLACE FUNCTION private.capture_canonical_festival_stage_evidence()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $canonical_event$
DECLARE
  v_runtime public.festival_edition_runtimes%ROWTYPE;
  v_stage_id uuid;
  v_item_id uuid;
  v_date date;
  v_observed_at timestamptz;
  v_timezone text;
  v_status text;
  v_previous_status text;
  v_previous_at timestamptz;
BEGIN
  IF NEW.evidence_type NOT IN
    ('stage_ready','stage_soundcheck','stage_changeover','stage_starting','stage_live','stage_delayed','stage_completed','stage_cancelled')
  THEN RETURN NEW; END IF;

  IF jsonb_typeof(NEW.evidence) IS DISTINCT FROM 'object' THEN
    RAISE EXCEPTION 'festival_stage_evidence_invalid';
  END IF;

  -- Status is sourced from the trusted evidence type, never untrusted JSON.
  v_status := substring(NEW.evidence_type FROM 7);
  v_stage_id := (NEW.evidence->>'stageId')::uuid;
  v_item_id := (NEW.evidence->>'scheduleItemId')::uuid;
  v_date := (NEW.evidence->>'festivalDate')::date;
  v_observed_at := (NEW.evidence->>'observedAt')::timestamptz;
  IF v_stage_id IS NULL OR v_item_id IS NULL OR v_date IS NULL OR v_observed_at IS NULL THEN
    RAISE EXCEPTION 'festival_stage_evidence_missing_identity';
  END IF;

  SELECT * INTO v_runtime
  FROM public.festival_edition_runtimes r WHERE r.id=NEW.runtime_id;
  IF NOT FOUND OR v_runtime.state NOT IN ('gates_open','live','paused','closing') THEN
    RAISE EXCEPTION 'festival_stage_runtime_inactive';
  END IF;

  -- Require the stage to belong to the *same* canonical annual edition.
  IF NOT EXISTS (
    SELECT 1 FROM public.festival_site_plan_stages st
    JOIN public.festival_site_plans p ON p.id=st.festival_site_plan_id
    WHERE st.id=v_stage_id AND st.status='ready'
      AND p.festival_edition_id=v_runtime.edition_id
      AND p.festival_company_id=v_runtime.festival_company_id
  ) THEN RAISE EXCEPTION 'festival_stage_wrong_edition'; END IF;

  -- Require the stage+artist item to have been generated by THIS runtime.
  IF NOT EXISTS (
    SELECT 1 FROM jsonb_array_elements(
      coalesce(v_runtime.generated_schedule->'items','[]'::jsonb)
    ) AS item
    WHERE item->>'id'=v_item_id::text
      AND item->>'stageId'=v_stage_id::text
      AND item->>'festivalDate'=v_date::text
  ) THEN RAISE EXCEPTION 'festival_stage_item_not_in_runtime'; END IF;

  SELECT coalesce(v_runtime.generated_schedule->>'timezone',nullif(c.timezone,''),'UTC') INTO v_timezone
  FROM public.festival_editions_v2 e
  JOIN public.cities c ON c.id=e.city_id
  WHERE e.id=v_runtime.edition_id
    AND v_date BETWEEN e.starts_on AND e.ends_on;
  IF v_timezone IS NULL OR (v_observed_at AT TIME ZONE v_timezone)::date <> v_date
     OR v_observed_at < NEW.created_at - interval '15 minutes'
     OR v_observed_at > NEW.created_at + interval '1 minute' THEN
    RAISE EXCEPTION 'festival_stage_observation_out_of_day';
  END IF;

  -- Serialize transitions for this particular scheduled act; multiple
  -- workers must never race each other into contradictory stage states.
  PERFORM pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(NEW.runtime_id::text || ':' || v_item_id::text, 0)
  );
  SELECT e.event_status, e.observed_at INTO v_previous_status, v_previous_at
  FROM private.festival_edition_stage_events e
  WHERE e.runtime_id = NEW.runtime_id AND e.schedule_item_id = v_item_id
  ORDER BY e.observed_at DESC, e.recorded_at DESC LIMIT 1;

  IF v_previous_status IS NULL AND v_status NOT IN ('ready','changeover','soundcheck','delayed','cancelled') THEN
    RAISE EXCEPTION 'festival_stage_missing_initial_state';
  ELSIF v_previous_status IS NOT NULL AND (
    v_observed_at <= v_previous_at
    OR NOT (
      (v_previous_status='ready' AND v_status IN ('changeover','soundcheck','starting','delayed','cancelled'))
      OR (v_previous_status='changeover' AND v_status IN ('soundcheck','starting','delayed','cancelled'))
      OR (v_previous_status='soundcheck' AND v_status IN ('starting','delayed','cancelled'))
      OR (v_previous_status='starting' AND v_status IN ('live','delayed','cancelled'))
      OR (v_previous_status='live' AND v_status IN ('delayed','completed','cancelled'))
      OR (v_previous_status='delayed' AND v_status IN ('changeover','soundcheck','starting','live','cancelled'))
    )
  ) THEN
    RAISE EXCEPTION 'festival_stage_invalid_event_transition';
  END IF;

  INSERT INTO private.festival_edition_stage_events(
    runtime_id,edition_id,stage_id,schedule_item_id,source_evidence_id,
    event_status,festival_date,observed_at
  ) VALUES (
    NEW.runtime_id,v_runtime.edition_id,v_stage_id,v_item_id,NEW.id,
    v_status,v_date,v_observed_at
  );
  RETURN NEW;
END;
$canonical_event$;

REVOKE ALL ON FUNCTION private.capture_canonical_festival_stage_evidence()
  FROM PUBLIC, anon, authenticated, service_role;

CREATE OR REPLACE FUNCTION public.record_canonical_festival_stage_action(
 p_runtime_id uuid,p_stage_id uuid,p_schedule_item_id uuid,
 p_status text,p_idempotency_key text,p_expected_runtime_version integer DEFAULT NULL
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=''
AS $body$
DECLARE
 v_runtime public.festival_edition_runtimes%ROWTYPE;
 v_edition public.festival_editions_v2%ROWTYPE;
 v_actor uuid:=public._caller_profile_id();
 v_owner uuid;
 v_timezone text;
 v_day date;
 v_item jsonb;
 v_hash text;
 v_receipt private.festival_edition_stage_action_receipts%ROWTYPE;
 v_evidence_id uuid;
 v_at timestamptz;
BEGIN
 IF auth.uid() IS NULL OR v_actor IS NULL THEN RAISE EXCEPTION 'festival_stage_action_unauthorised'; END IF;
 IF p_status IS NULL OR p_stage_id IS NULL OR p_schedule_item_id IS NULL OR p_status NOT IN ('ready','changeover','soundcheck','starting','live','delayed','completed','cancelled')
    OR p_idempotency_key IS NULL OR length(p_idempotency_key) NOT BETWEEN 12 AND 128 THEN
  RAISE EXCEPTION 'festival_stage_action_invalid';
 END IF;
 SELECT * INTO v_runtime FROM public.festival_edition_runtimes WHERE id=p_runtime_id FOR UPDATE;
 IF NOT FOUND OR EXISTS (
   SELECT 1 FROM public.festival_edition_runtimes newer
   WHERE newer.edition_id=v_runtime.edition_id
     AND (newer.created_at,newer.id)>(v_runtime.created_at,v_runtime.id)
 ) THEN RAISE EXCEPTION 'festival_stage_runtime_not_found'; END IF;
 SELECT owner_profile_id INTO v_owner FROM public.festival_companies WHERE id=v_runtime.festival_company_id;
 IF v_owner IS DISTINCT FROM v_actor
    AND NOT coalesce(public.has_role(auth.uid(),'admin'::public.app_role),false) THEN
  RAISE EXCEPTION 'festival_stage_action_forbidden';
 END IF;
 v_hash:=md5(p_stage_id::text||':'||p_schedule_item_id::text||':'||p_status);
 SELECT * INTO v_receipt FROM private.festival_edition_stage_action_receipts
 WHERE runtime_id=p_runtime_id AND idempotency_key=p_idempotency_key;
 IF FOUND THEN
  IF v_hash IS DISTINCT FROM v_receipt.request_hash THEN RAISE EXCEPTION 'festival_stage_action_idempotency_conflict'; END IF;
  RETURN jsonb_build_object('sourceEvidenceId',v_receipt.source_evidence_id,'status',p_status,'replayed',true);
 END IF;
 IF p_expected_runtime_version IS NOT NULL AND p_expected_runtime_version<>v_runtime.version
 THEN RAISE EXCEPTION 'festival_stage_runtime_stale'; END IF;
 IF (p_status='ready' AND v_runtime.state NOT IN ('gates_open','live'))
    OR (p_status<>'ready' AND v_runtime.state<>'live') THEN
  RAISE EXCEPTION 'festival_stage_runtime_not_live';
 END IF;
 SELECT * INTO v_edition FROM public.festival_editions_v2
 WHERE id=v_runtime.edition_id AND festival_company_id=v_runtime.festival_company_id;
 IF NOT FOUND THEN RAISE EXCEPTION 'festival_stage_wrong_edition'; END IF;
 SELECT coalesce(v_runtime.generated_schedule->>'timezone',nullif(timezone,'')) INTO v_timezone
 FROM public.cities WHERE id=v_edition.city_id;
 IF v_timezone IS NULL THEN RAISE EXCEPTION 'festival_stage_timezone_missing'; END IF;
 v_at:=clock_timestamp();
 v_day:=(v_at AT TIME ZONE v_timezone)::date;
 IF v_day NOT BETWEEN v_edition.starts_on AND v_edition.ends_on
 THEN RAISE EXCEPTION 'festival_stage_outside_festival_day'; END IF;
 IF NOT EXISTS (
  SELECT 1 FROM public.festival_site_plan_stages s
  JOIN public.festival_site_plans p ON p.id=s.festival_site_plan_id
  WHERE s.id=p_stage_id AND s.status='ready'
    AND p.festival_edition_id=v_runtime.edition_id
    AND p.festival_company_id=v_runtime.festival_company_id
 ) THEN RAISE EXCEPTION 'festival_stage_not_published_for_edition'; END IF;
 SELECT item.value INTO v_item
 FROM jsonb_array_elements(coalesce(v_runtime.generated_schedule->'items','[]'::jsonb)) item
 WHERE item.value->>'id'=p_schedule_item_id::text
   AND item.value->>'stageId'=p_stage_id::text
   AND item.value->>'festivalDate'=v_day::text LIMIT 1;
 IF v_item IS NULL THEN RAISE EXCEPTION 'festival_stage_slot_identity_mismatch'; END IF;
 -- Never announce a withdrawn or cross-edition artist booking as performing.
 IF p_status IN ('ready','changeover','soundcheck','starting','live') AND nullif(v_item->>'sourceBookingId','') IS NOT NULL
   AND NOT EXISTS (
     SELECT 1 FROM public.festival_artist_bookings b
     JOIN public.festival_artist_programmes prog ON prog.id=b.festival_artist_programme_id
     WHERE b.id=(v_item->>'sourceBookingId')::uuid
       AND prog.festival_edition_id=v_runtime.edition_id
       AND b.status IN ('confirmed','awaiting_schedule','scheduled')
       AND b.band_id::text IS NOT DISTINCT FROM v_item->>'bandId'
   )
 THEN RAISE EXCEPTION 'festival_stage_artist_booking_unverified'; END IF;

 -- One preparing or performing act per stage. The same runtime-row lock serialises
 -- workers, and only the latest state of each *other* act is considered.
 IF p_status IN ('changeover','soundcheck','starting','live') AND EXISTS (
   SELECT 1 FROM (
     SELECT DISTINCT ON (schedule_item_id) schedule_item_id,event_status
     FROM private.festival_edition_stage_events
     WHERE runtime_id=v_runtime.id AND stage_id=p_stage_id
       AND festival_date=v_day AND schedule_item_id<>p_schedule_item_id
     ORDER BY schedule_item_id,observed_at DESC,recorded_at DESC
   ) current_on_stage
   WHERE current_on_stage.event_status IN ('changeover','soundcheck','starting','live')
 ) THEN RAISE EXCEPTION 'festival_stage_overlap_not_permitted'; END IF;

 INSERT INTO public.festival_runtime_evidence(runtime_id,evidence_type,evidence,evidence_digest)
 VALUES (
  p_runtime_id,'stage_'||p_status,
  jsonb_build_object(
   'stageId',p_stage_id,'scheduleItemId',p_schedule_item_id,'festivalDate',v_day,
   'observedAt',v_at,'source','operator_confirmed',
   'confirmedByProfileId',v_actor,
   'artistIdentity',jsonb_build_object('bandId',v_item->>'bandId','bookingId',v_item->>'sourceBookingId'),
   'actionId',p_idempotency_key
  ),
  md5(p_runtime_id::text||':'||p_idempotency_key||':'||v_hash)
 ) RETURNING id INTO v_evidence_id;
 -- The existing canonical stage-event trigger validates transitions atomically.
 INSERT INTO private.festival_edition_stage_action_receipts(runtime_id,idempotency_key,request_hash,source_evidence_id)
 VALUES(p_runtime_id,p_idempotency_key,v_hash,v_evidence_id);
 RETURN jsonb_build_object('sourceEvidenceId',v_evidence_id,'status',p_status,'stageId',p_stage_id,
  'scheduleItemId',p_schedule_item_id,'observedAt',v_at,'replayed',false);
END;
$body$;
REVOKE ALL ON FUNCTION public.record_canonical_festival_stage_action(uuid,uuid,uuid,text,text,integer)
 FROM PUBLIC,anon,authenticated,service_role;
GRANT EXECUTE ON FUNCTION public.record_canonical_festival_stage_action(uuid,uuid,uuid,text,text,integer)
 TO authenticated;


CREATE OR REPLACE FUNCTION public.get_public_festival_edition_live_status(p_slug text)
RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = ''
AS $festival_public$
DECLARE
  v_launch_id uuid;
  v_company_id uuid;
  v_public jsonb;
  v_edition_id uuid;
  v_edition public.festival_editions_v2%ROWTYPE;
  v_runtime public.festival_edition_runtimes%ROWTYPE;
  v_timezone text;
  v_today date;
  v_day date;
  v_active boolean;
  v_weather jsonb;
  v_weather_state text;
  v_attendance_band text;
  v_runtime_status text;
  v_performances jsonb := '[]'::jsonb;
  v_stage_crowds jsonb := '[]'::jsonb;
  v_latest_stage_at timestamptz;
  v_latest_crowd_at timestamptz;
BEGIN
  IF p_slug IS NULL OR length(p_slug) > 128 OR p_slug !~ '^[a-z0-9]+(?:-[a-z0-9]+)*$' THEN
    RETURN NULL;
  END IF;

  -- A public/unlisted launch is the only permitted entry point. This also
  -- prevents access to private, cancelled and draft festivals by guessed slug.
  SELECT l.id, l.festival_company_id INTO v_launch_id, v_company_id
  FROM public.festival_launches l
  LEFT JOIN public.festival_public_profiles p ON p.festival_company_id = l.festival_company_id
  WHERE (l.public_slug = p_slug OR p.public_slug = p_slug)
    AND l.public_visibility IN ('public','unlisted')
    AND l.launch_status IN ('launched','tickets_on_sale','sales_paused','sales_closed')
  LIMIT 1;
  IF v_launch_id IS NULL THEN RETURN NULL; END IF;

  -- Reuse the already-published edition identity. Never infer an edition from
  -- the newest runtime for a company or treat a launch ID as an edition ID.
  v_public := public.festival_public_projection_v2(v_company_id);
  IF v_public IS NULL OR v_public->>'id' IS DISTINCT FROM v_launch_id::text
      OR coalesce(v_public->>'editionId','') = '' THEN
    RETURN NULL;
  END IF;
  v_edition_id := (v_public->>'editionId')::uuid;

  SELECT * INTO v_edition
  FROM public.festival_editions_v2 e
  WHERE e.id = v_edition_id AND e.festival_company_id = v_company_id
    AND e.status NOT IN ('cancelled','cancelled_before_event');
  IF NOT FOUND THEN RETURN NULL; END IF;

  SELECT * INTO v_runtime
  FROM public.festival_edition_runtimes r
  WHERE r.edition_id = v_edition.id AND r.festival_company_id = v_company_id
  ORDER BY r.created_at DESC, r.id DESC LIMIT 1;
  IF NOT FOUND THEN RETURN NULL; END IF;

  SELECT coalesce(v_runtime.generated_schedule->>'timezone',nullif(c.timezone,''),'UTC') INTO v_timezone
  FROM public.cities c WHERE c.id = v_edition.city_id;
  v_today := (now() AT TIME ZONE coalesce(v_timezone,'UTC'))::date;
  v_active := v_today BETWEEN v_edition.starts_on AND v_edition.ends_on
              AND v_runtime.state IN ('gates_open','live','paused');
  v_day := CASE WHEN v_active THEN v_today ELSE NULL END;

  v_runtime_status := CASE v_runtime.state
    WHEN 'preparing' THEN 'pre_event'
    WHEN 'ready' THEN 'ready_to_open'
    WHEN 'gates_open' THEN 'gates_open'
    WHEN 'live' THEN 'live'
    WHEN 'paused' THEN 'paused'
    WHEN 'closing' THEN 'public_closed'
    WHEN 'completed' THEN 'runtime_complete'
    WHEN 'aborted' THEN 'cancelled'
    WHEN 'recovery_required' THEN 'emergency_hold'
    ELSE 'pre_event'
  END;

  -- Public attendance comes from the latest current-day recorded observation.
  IF v_active AND v_runtime.site_capacity > 0 AND EXISTS (
    SELECT 1 FROM public.festival_runtime_evidence obs
    WHERE obs.runtime_id=v_runtime.id AND obs.evidence_type='live_day_tick'
      AND obs.evidence->>'festivalDate'=v_today::text
      AND obs.created_at BETWEEN now() - interval '10 minutes' AND now()
  ) THEN
    v_attendance_band := CASE
      WHEN v_runtime.site_attendance >= v_runtime.site_capacity THEN 'full'
      WHEN v_runtime.site_attendance >= v_runtime.site_capacity * 0.9 THEN 'near_capacity'
      WHEN v_runtime.site_attendance >= v_runtime.site_capacity * 0.7 THEN 'very_busy'
      WHEN v_runtime.site_attendance >= v_runtime.site_capacity * 0.4 THEN 'busy'
      WHEN v_runtime.site_attendance >= v_runtime.site_capacity * 0.15 THEN 'building'
      ELSE 'quiet'
    END;
  END IF;

  -- The preserved weather_sequence is indexed by day of the edition; do not
  -- display a different festival day's conditions or invent a fallback.
  IF v_active AND jsonb_typeof(v_runtime.weather_sequence) = 'array' THEN
    v_weather := v_runtime.weather_sequence -> (v_day - v_edition.starts_on);
    v_weather_state := v_weather->>'condition';
    IF v_weather_state NOT IN
      ('clear','cloudy','light_rain','heavy_rain','hot','cold','high_wind','storm') THEN
      v_weather_state := NULL;
    END IF;
  END IF;


  -- Performance state comes ONLY from canonical runtime evidence, not from
  -- generated_schedule clock values. The same runtime, edition, site plan,
  -- stage and current festival day must match. Paused/closed runtime hides
  -- current live claims even if a prior event said "live".
  IF v_active AND v_runtime.state = 'live' THEN
    SELECT coalesce(jsonb_agg(jsonb_build_object(
      'id', latest.schedule_item_id,
      'stageId', latest.stage_id,
      'stageName', stage.name,
      'artistName', item.value->>'artistName',
      'scheduledStart', NULL,
      'scheduledEnd', NULL,
      'status', latest.event_status,
      'delayMinutes', 0,
      'observedAt', latest.observed_at
    ) ORDER BY latest.observed_at DESC), '[]'::jsonb),
    max(latest.observed_at)
    INTO v_performances, v_latest_stage_at
    FROM (
      SELECT DISTINCT ON (ev.schedule_item_id)
        ev.schedule_item_id, ev.stage_id, ev.festival_date,
        ev.event_status, ev.observed_at
      FROM private.festival_edition_stage_events ev
      WHERE ev.runtime_id=v_runtime.id
        AND ev.edition_id=v_edition.id
        AND ev.festival_date=v_day
      ORDER BY ev.schedule_item_id, ev.observed_at DESC, ev.recorded_at DESC
    ) latest
    JOIN LATERAL jsonb_array_elements(
      coalesce(v_runtime.generated_schedule->'items', '[]'::jsonb)
    ) item ON item.value->>'id'=latest.schedule_item_id::text
      AND item.value->>'stageId'=latest.stage_id::text
      AND item.value->>'festivalDate'=v_day::text
    JOIN public.festival_site_plan_stages stage ON stage.id=latest.stage_id
    JOIN public.festival_site_plans plan ON plan.id=stage.festival_site_plan_id
    WHERE plan.festival_edition_id=v_edition.id
      AND plan.festival_company_id=v_company_id
      AND stage.status='ready'
      AND latest.observed_at <= now() + interval '1 minute'
      AND (
        (latest.event_status IN ('ready','changeover','soundcheck','starting','live','delayed')
          AND latest.observed_at >= now() - interval '10 minutes')
        OR (latest.event_status IN ('completed','cancelled')
          AND latest.observed_at >= now() - interval '2 hours')
      );
  END IF;

  -- Never derive stage occupancy from overall attendance. Stage-specific
  -- snapshots must be recent, measured/allocated, and tied to the same
  -- runtime, edition, site-plan stage and current local festival day.
  IF v_active AND v_runtime.state IN ('live','gates_open') THEN
    SELECT coalesce(jsonb_agg(jsonb_build_object(
      'stageId', latest.stage_id,
      'stageName', stage.name,
      'festivalDate', latest.festival_date,
      'lastCalculatedAt', latest.observed_at,
      'crowdBand', CASE
        WHEN latest.observed_audience >= latest.stage_capacity THEN 'full'
        WHEN latest.observed_audience >= latest.stage_capacity * 0.90 THEN 'near_capacity'
        WHEN latest.observed_audience >= latest.stage_capacity * 0.70 THEN 'very_busy'
        WHEN latest.observed_audience >= latest.stage_capacity * 0.40 THEN 'busy'
        WHEN latest.observed_audience >= latest.stage_capacity * 0.15 THEN 'building'
        ELSE 'quiet' END,
      'mood', latest.crowd_mood
    ) ORDER BY stage.sort_order), '[]'::jsonb), max(latest.observed_at)
    INTO v_stage_crowds,v_latest_crowd_at
    FROM (
      SELECT DISTINCT ON (s.stage_id) s.*
      FROM private.festival_edition_stage_crowd_observations s
      WHERE s.runtime_id=v_runtime.id AND s.edition_id=v_edition.id
        AND s.festival_date=v_day
      ORDER BY s.stage_id,s.observed_at DESC,s.recorded_at DESC
    ) latest
    JOIN public.festival_site_plan_stages stage ON stage.id=latest.stage_id
    JOIN public.festival_site_plans plan ON plan.id=stage.festival_site_plan_id
    WHERE plan.festival_edition_id=v_edition.id
      AND plan.festival_company_id=v_company_id
      AND stage.status='ready'
      AND latest.observed_at >= now() - interval '10 minutes'
      AND latest.observed_at <= now() + interval '1 minute';
  END IF;

  RETURN jsonb_build_object(
    'festivalLaunchId', v_launch_id,
    'editionId', v_edition_id,
    'runtimeStatus', v_runtime_status,
    'gatesStatus', CASE WHEN v_runtime.state IN ('gates_open','live') AND v_active THEN 'open' ELSE 'closed' END,
    'currentDay', v_day,
    'attendanceBand', v_attendance_band,
    'performances', v_performances,
    'messages', '[]'::jsonb,
    'weather', CASE WHEN v_weather_state IS NOT NULL
      THEN jsonb_build_object('state',v_weather_state,'groundCondition',NULL)
      ELSE NULL END,
    'stageCrowds', v_stage_crowds,
    'updatedAt', greatest(v_runtime.updated_at, coalesce(v_latest_stage_at,v_runtime.updated_at), coalesce(v_latest_crowd_at,v_runtime.updated_at))
  );
END;
$festival_public$;

