-- Phase 1: Add rehearsal stage tracking to band_song_familiarity
ALTER TABLE public.band_song_familiarity
  ADD COLUMN IF NOT EXISTS rehearsal_stage text
  GENERATED ALWAYS AS (
    CASE
      WHEN familiarity_minutes < 21 THEN 'unrehearsed'
      WHEN familiarity_minutes < 41 THEN 'tight'
      ELSE 'perfect'
    END
  ) STORED;

-- Phase 2: Unify release systems - add release_id to song_releases
ALTER TABLE public.song_releases
  ADD COLUMN IF NOT EXISTS release_id uuid REFERENCES public.releases(id) ON DELETE CASCADE;

CREATE INDEX IF NOT EXISTS idx_song_releases_release_id
  ON public.song_releases (release_id);

-- Phase 3: Extend chart_entries for comprehensive charts
ALTER TABLE public.chart_entries
  ADD COLUMN IF NOT EXISTS sale_type text DEFAULT 'stream'
    CHECK (sale_type IN ('stream', 'digital', 'cd', 'vinyl', 'record')),
  ADD COLUMN IF NOT EXISTS country text,
  ADD COLUMN IF NOT EXISTS genre text;

CREATE INDEX IF NOT EXISTS idx_chart_entries_sale_type
  ON public.chart_entries (sale_type);
CREATE INDEX IF NOT EXISTS idx_chart_entries_country
  ON public.chart_entries (country);
CREATE INDEX IF NOT EXISTS idx_chart_entries_genre
  ON public.chart_entries (genre);

-- Phase 4: Create streaming analytics daily table
CREATE TABLE IF NOT EXISTS public.streaming_analytics_daily (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  song_release_id uuid NOT NULL REFERENCES public.song_releases(id) ON DELETE CASCADE,
  analytics_date date NOT NULL DEFAULT current_date,
  daily_streams integer DEFAULT 0,
  daily_revenue integer DEFAULT 0,
  unique_listeners integer DEFAULT 0,
  skip_rate decimal(5,2),
  completion_rate decimal(5,2),
  platform_id uuid REFERENCES public.streaming_platforms(id),
  created_at timestamptz DEFAULT now(),
  UNIQUE(song_release_id, analytics_date, platform_id)
);

ALTER TABLE public.streaming_analytics_daily ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Users can view their own streaming analytics"
  ON public.streaming_analytics_daily;
CREATE POLICY "Users can view their own streaming analytics"
  ON public.streaming_analytics_daily
  FOR SELECT
  TO authenticated
  USING (
    EXISTS (
      SELECT 1
      FROM public.song_releases sr
      JOIN public.songs s ON s.id = sr.song_id
      WHERE sr.id = streaming_analytics_daily.song_release_id
        AND (
          s.artist_id = auth.uid()
          OR EXISTS (
            SELECT 1
            FROM public.band_members bm
            WHERE bm.band_id = s.band_id
              AND bm.user_id = auth.uid()
          )
        )
    )
  );

-- Daily analytics are generated by trusted scheduled/server processes, not by
-- player clients.
DROP POLICY IF EXISTS "System can insert streaming analytics"
  ON public.streaming_analytics_daily;
CREATE POLICY "System can insert streaming analytics"
  ON public.streaming_analytics_daily
  FOR INSERT
  TO service_role
  WITH CHECK (true);

CREATE INDEX IF NOT EXISTS idx_streaming_analytics_date
  ON public.streaming_analytics_daily (analytics_date DESC);
CREATE INDEX IF NOT EXISTS idx_streaming_analytics_song_release
  ON public.streaming_analytics_daily (song_release_id);

COMMENT ON TABLE public.streaming_analytics_daily IS
  'Daily granular streaming analytics for detailed performance tracking';
COMMENT ON COLUMN public.band_song_familiarity.rehearsal_stage IS
  'Auto-calculated rehearsal stage: unrehearsed (<21 min), tight (21-40 min), perfect (41-60 min)';

