-- 19 Oct 2026: protect registered Battle of the Bands from premature
-- settlement, and serialize cron scheduling with mayor reschedules.
-- Forward-only; preserves scheduled dates, history, rewards and treasuries.

DO $preflight$
BEGIN
  IF position('IF v_event.status <> ''upcoming'' THEN' IN
        pg_get_functiondef('public.resolve_botb_event(uuid)'::regprocedure)) = 0
    OR position('FROM public.botb_estimate_event_finances(p_event_id)' IN
        pg_get_functiondef('public.resolve_botb_event(uuid)'::regprocedure)) = 0
    OR position('IF v_event.status <> ''upcoming'' THEN' IN
        pg_get_functiondef('public.botb_check_eligibility(uuid,uuid)'::regprocedure)) = 0
    OR position('v_count := v_count + 1;' IN
        pg_get_functiondef('public.generate_botb_events(integer)'::regprocedure)) = 0
  THEN
    RAISE EXCEPTION 'BOTB functions drifted: stop and review before applying';
  END IF;
END;
$preflight$;

-- Cron and the mayor RPC both take a cities row lock. Read each city's
-- settings in a NEW statement AFTER the lock: that way a simultaneous
-- mayor edit cannot leave stale prize/date rows generated by the cron.
CREATE OR REPLACE FUNCTION public.generate_botb_events(p_horizon_events integer DEFAULT 3)
RETURNS integer
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $generate$
DECLARE
  v_city record;
  v_weekday integer;
  v_frequency_weeks integer;
  v_prize_money integer;
  v_anchor_date date;
  v_today date;
  v_local_date date;
  v_first integer;
  v_date timestamptz;
  v_i integer;
  v_created integer := 0;
  v_inserted integer;
  v_count integer;
  v_horizon integer := LEAST(12,GREATEST(1,COALESCE(p_horizon_events,3)));
BEGIN
  FOR v_city IN
    SELECT c.id,COALESCE(NULLIF(c.timezone,''),'UTC') AS city_timezone
    FROM public.cities c ORDER BY c.id FOR UPDATE OF c
  LOOP
    -- Every subsequent statement uses READ COMMITTED's fresh snapshot.
    SELECT COALESCE(s.weekday,5), COALESCE(s.frequency_weeks,2),
           COALESCE(s.prize_money,5000)
    INTO v_weekday,v_frequency_weeks,v_prize_money
    FROM public.botb_city_settings s WHERE s.city_id=v_city.id;
    IF NOT FOUND THEN
      v_weekday:=5; v_frequency_weeks:=2; v_prize_money:=5000;
    END IF;

    v_anchor_date := date '2026-01-02' + (v_weekday - 5);
    v_today := (now() AT TIME ZONE v_city.city_timezone)::date;
    v_first := GREATEST(0,CEIL(
      (v_today - v_anchor_date)::numeric / (v_frequency_weeks * 7)
    )::integer);
    v_count := 0;

    -- The additional loop headroom accounts for grandfathered legacy times.
    FOR v_i IN 0..(v_horizon + 12) LOOP
      v_local_date := v_anchor_date + ((v_first + v_i) * v_frequency_weeks * 7);
      v_date := (v_local_date::timestamp + interval '19 hours')
        AT TIME ZONE v_city.city_timezone;
      IF v_date <= now() THEN CONTINUE; END IF;

      IF EXISTS (
        SELECT 1 FROM public.botb_events existing
        WHERE existing.city_id=v_city.id AND existing.status='upcoming'
          AND existing.scheduled_date>now()
          AND (existing.scheduled_date AT TIME ZONE v_city.city_timezone)::date=v_local_date
      ) THEN
        v_count := v_count + 1;
        IF v_count >= v_horizon THEN EXIT; END IF;
        CONTINUE;
      END IF;

      INSERT INTO public.botb_events(city_id,scheduled_date,prize_money)
      VALUES(v_city.id,v_date,v_prize_money)
      ON CONFLICT(city_id,scheduled_date) DO NOTHING;
      GET DIAGNOSTICS v_inserted=ROW_COUNT;
      v_created:=v_created+v_inserted;
      v_count:=v_count+1;
      IF v_count >= v_horizon THEN EXIT; END IF;
    END LOOP;
  END LOOP;
  RETURN v_created;
END;
$generate$;
REVOKE ALL ON FUNCTION public.generate_botb_events(integer)
  FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.generate_botb_events(integer) TO service_role;

DO $patch_functions$
DECLARE
  v_old text;
  v_new text;
BEGIN
  -- A service worker or accidental manual RPC must never award a prize, XP
  -- or fame early, even if the caller has permission to run the resolver.
  v_old := pg_get_functiondef('public.resolve_botb_event(uuid)'::regprocedure);
  IF position('''reason'', ''not_due''' IN v_old)>0 THEN
    RAISE EXCEPTION 'BOTB resolver already has due guard: reconcile migration';
  END IF;
  v_new := replace(v_old,
$old$  IF v_event.status <> 'upcoming' THEN
    RETURN jsonb_build_object('success', false, 'reason', 'already_resolved');
  END IF;$old$,
$new$  IF v_event.status <> 'upcoming' THEN
    RETURN jsonb_build_object('success', false, 'reason', 'already_resolved');
  END IF;
  IF v_event.scheduled_date > now() THEN
    RETURN jsonb_build_object('success', false, 'reason', 'not_due');
  END IF;$new$);
  IF v_old=v_new THEN
    RAISE EXCEPTION 'BOTB resolver expected insertion point missing';
  END IF;
  EXECUTE v_new;

  -- The public eligibility read should never tell a band it can sign up
  -- after doors close, even in the gap before the scheduled cron fires.
  v_old := pg_get_functiondef('public.botb_check_eligibility(uuid,uuid)'::regprocedure);
  v_new := replace(v_old,
$old$  IF v_event.status <> 'upcoming' THEN
    RETURN jsonb_build_object('eligible', false, 'reason', 'This battle is no longer open');
  END IF;$old$,
$new$  IF v_event.status <> 'upcoming' OR v_event.scheduled_date <= now() THEN
    RETURN jsonb_build_object('eligible', false, 'reason', 'This battle is no longer open');
  END IF;$new$);
  IF v_old=v_new THEN
    RAISE EXCEPTION 'BOTB eligibility expected insertion point missing';
  END IF;
  EXECUTE v_new;
END;
$patch_functions$;

REVOKE ALL ON FUNCTION public.botb_check_eligibility(uuid,uuid)
  FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.botb_check_eligibility(uuid,uuid)
  TO authenticated,service_role;
REVOKE ALL ON FUNCTION public.resolve_botb_event(uuid)
  FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.resolve_botb_event(uuid)
  TO service_role;
