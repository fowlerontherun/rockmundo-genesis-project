CREATE FUNCTION public.get_canonical_festival_live_day_availability(p_company_id uuid,p_edition_id uuid)
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path=''
AS $availability$
DECLARE
 actor uuid := public._caller_profile_id();
 e public.festival_editions_v2%ROWTYPE;
 r public.festival_edition_runtimes%ROWTYPE;
 cfg jsonb;
 zone text;
 local_day date;
BEGIN
 IF auth.uid() IS NULL OR actor IS NULL OR NOT coalesce(public._festival_edition_runtime_authorised(
   p_company_id,p_edition_id,actor),false)
 THEN RAISE EXCEPTION 'festival_runtime_forbidden'; END IF;
 SELECT * INTO e FROM public.festival_editions_v2
 WHERE id=p_edition_id AND festival_company_id=p_company_id;
 IF NOT FOUND THEN RAISE EXCEPTION 'festival_edition_not_found'; END IF;
 SELECT * INTO r FROM public.festival_edition_runtimes
 WHERE edition_id=e.id ORDER BY created_at DESC,id DESC LIMIT 1;
 SELECT configuration INTO cfg FROM public.festival_runtime_configuration_versions
 WHERE runtime_id=r.id AND rules_version='canonical-live-day-v1';
 SELECT c.timezone INTO zone FROM public.cities c
 WHERE c.id=e.city_id AND EXISTS (SELECT 1 FROM pg_catalog.pg_timezone_names WHERE name=c.timezone);
 local_day := (now() AT TIME ZONE coalesce(cfg->>'timezone',zone))::date;
 RETURN jsonb_build_object(
   'canOpen',coalesce(r.id IS NULL AND local_day=e.starts_on AND e.status IN ('locked','announced'),false),
   'managed',cfg IS NOT NULL,
   'canAllocate',coalesce(cfg IS NOT NULL AND r.state IN ('gates_open','live')
     AND local_day BETWEEN (cfg->>'startsOn')::date AND (cfg->>'endsOn')::date,false)
 );
END;
$availability$;
REVOKE ALL ON FUNCTION public.get_canonical_festival_live_day_availability(uuid,uuid)
 FROM PUBLIC, anon, authenticated, service_role;
GRANT EXECUTE ON FUNCTION public.get_canonical_festival_live_day_availability(uuid,uuid)
 TO authenticated;

COMMIT;
