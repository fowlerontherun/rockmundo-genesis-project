CREATE OR REPLACE FUNCTION public.start_canonical_festival_live_day(p_festival_company_id uuid, p_festival_edition_id uuid, p_expected_edition_version integer, p_idempotency_key uuid)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'pg_catalog', 'extensions'
AS $function$
DECLARE
  actor uuid := public._caller_profile_id();
  e public.festival_editions_v2%ROWTYPE;
  readiness jsonb;
  prior public.festival_edition_runtimes%ROWTYPE;
  r public.festival_edition_runtimes%ROWTYPE;
  site public.festival_site_plans%ROWTYPE;
  ticket public.festival_ticket_plans%ROWTYPE;
  programme public.festival_artist_programmes%ROWTYPE;
  generated jsonb;
  expected int;
  seed bigint;
  config jsonb;
  config_digest text;
  licensed_acts_per_day integer;
  stage_count integer;
  booked_count integer;
  duration_days integer;
  slots_per_day integer;
  target_slots integer;
  zone text;
  observed_at timestamptz;
BEGIN
  IF auth.uid() IS NULL OR actor IS NULL OR NOT public._festival_edition_runtime_authorised(p_festival_company_id, p_festival_edition_id, actor) THEN
    RAISE EXCEPTION 'festival_runtime_forbidden' USING ERRCODE = 'P0001';
  END IF;

  IF p_idempotency_key IS NULL THEN
    RAISE EXCEPTION 'festival_runtime_idempotency_required' USING ERRCODE = 'P0001';
  END IF;

  PERFORM pg_advisory_xact_lock(hashtextextended(p_festival_edition_id::text, 0));

  SELECT * INTO prior
  FROM public.festival_edition_runtimes
  WHERE edition_id = p_festival_edition_id
    AND idempotency_key = p_idempotency_key::text
  LIMIT 1;

  IF FOUND THEN
    IF NOT EXISTS (
      SELECT 1 FROM public.festival_runtime_configuration_versions
      WHERE runtime_id=prior.id AND rules_version='canonical-live-day-v1'
    ) THEN RAISE EXCEPTION 'festival_live_start_key_conflict'; END IF;
    RETURN public._festival_runtime_projection(prior.id, actor);
  END IF;

  SELECT * INTO e
  FROM public.festival_editions_v2
  WHERE id = p_festival_edition_id
    AND festival_company_id = p_festival_company_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'festival_edition_not_found' USING ERRCODE = 'P0001';
  END IF;

  IF e.version IS DISTINCT FROM p_expected_edition_version THEN
    RAISE EXCEPTION 'festival_runtime_stale' USING ERRCODE = 'P0001';
  END IF;

  readiness := public._simplified_festival_run_readiness(p_festival_company_id, p_festival_edition_id);
  IF EXISTS (
    SELECT 1 FROM jsonb_array_elements(readiness->'blockers') blocker
    WHERE blocker->>'code' <> 'festival_not_due'
  ) THEN
    RAISE EXCEPTION 'festival_runtime_not_ready: %', readiness->'blockers' USING ERRCODE = 'P0001';
  END IF;

  SELECT * INTO site FROM public.festival_site_plans WHERE festival_edition_id = e.id;
  SELECT * INTO ticket FROM public.festival_ticket_plans WHERE festival_edition_id = e.id;
  SELECT * INTO programme FROM public.festival_artist_programmes WHERE festival_edition_id = e.id;
  SELECT c.timezone INTO zone FROM public.cities c
  WHERE c.id=e.city_id AND EXISTS (SELECT 1 FROM pg_timezone_names WHERE name=c.timezone);
  observed_at := clock_timestamp();
  IF zone IS NULL OR e.starts_on IS NULL OR e.ends_on IS NULL
     OR (observed_at AT TIME ZONE zone)::date <> e.starts_on
     OR e.status NOT IN ('locked','announced')
     OR EXISTS (SELECT 1 FROM public.festival_edition_runtimes WHERE edition_id=e.id)
  THEN RAISE EXCEPTION 'festival_live_start_unavailable'; END IF;

  duration_days := greatest(
    1,
    coalesce(
      e.duration_days,
      CASE
        WHEN e.starts_on IS NOT NULL AND e.ends_on IS NOT NULL THEN (e.ends_on - e.starts_on) + 1
        ELSE 1
      END
    )
  );
  licensed_acts_per_day := nullif((readiness->>'licensedActsPerDay')::integer, 0);

  SELECT count(*)::integer INTO stage_count
  FROM public.festival_site_plan_stages st
  WHERE st.festival_site_plan_id = site.id
    AND st.status = 'ready';

  SELECT count(*)::integer INTO booked_count
  FROM public.festival_artist_bookings b
  WHERE b.festival_artist_programme_id = programme.id
    AND b.status IN ('confirmed', 'awaiting_schedule', 'scheduled');

  slots_per_day := greatest(
    1,
    greatest(
      stage_count * 4,
      ceil(booked_count::numeric / duration_days)::integer
    )
  );
  IF licensed_acts_per_day IS NOT NULL THEN
    slots_per_day := least(slots_per_day, licensed_acts_per_day);
  END IF;
  target_slots := greatest(booked_count, slots_per_day * duration_days);

  seed := hashtextextended(e.id::text || p_idempotency_key::text, 0);
  expected := least(
    site.usable_capacity,
    greatest(
      0,
      coalesce(
        nullif(ticket.forecast->>'expectedTicketsSold', '')::int,
        round(site.usable_capacity * .8)::int
      )
    )
  );
  IF target_slots > slots_per_day * duration_days OR e.ends_on <> e.starts_on + duration_days - 1 THEN
    RAISE EXCEPTION 'festival_live_programme_exceeds_edition_dates';
  END IF;

  WITH stages AS (
    SELECT
      st.id,
      st.name,
      st.sort_order,
      st.capacity,
      row_number() OVER (ORDER BY st.sort_order, st.id) rn,
      count(*) OVER () cnt
    FROM public.festival_site_plan_stages st
    WHERE st.festival_site_plan_id = site.id
      AND st.status = 'ready'
  ), booked AS (
    SELECT
      b.id booking_id,
      b.artist_type,
      b.artist_profile_id,
      b.band_id,
      b.npc_artist_id,
      b.set_minutes,
      b.billing_position,
      b.provisional_date,
      coalesce(p.display_name, p.username, band.name, 'Confirmed act') artist_name,
      CASE b.billing_position
        WHEN 'emerging' THEN 10
        WHEN 'support' THEN 20
        WHEN 'special_guest' THEN 30
        WHEN 'featured' THEN 40
        WHEN 'sub_headliner' THEN 50
        WHEN 'headliner' THEN 60
        ELSE 20
      END bill_rank,
      row_number() OVER (
        ORDER BY
          CASE b.billing_position
            WHEN 'emerging' THEN 10
            WHEN 'support' THEN 20
            WHEN 'special_guest' THEN 30
            WHEN 'featured' THEN 40
            WHEN 'sub_headliner' THEN 50
            WHEN 'headliner' THEN 60
            ELSE 20
          END,
          b.confirmed_at,
          b.id
      ) rn
    FROM public.festival_artist_bookings b
    LEFT JOIN public.profiles p ON p.id = b.artist_profile_id
    LEFT JOIN public.bands band ON band.id = b.band_id
    WHERE b.festival_artist_programme_id = programme.id
      AND b.status IN ('confirmed', 'awaiting_schedule', 'scheduled')
  ), filler AS (
    SELECT gs n, 'NPC Festival Act ' || gs::text artist_name
    FROM generate_series(1, greatest(0, target_slots - booked_count)) gs
  ), items AS (
    SELECT
      0 grp,
      f.n ord,
      NULL::uuid booking_id,
      'npc'::text artist_type,
      NULL::uuid artist_profile_id,
      NULL::uuid band_id,
      NULL::uuid npc_artist_id,
      f.artist_name,
      'support'::text billing_position,
      45::int set_minutes,
      NULL::date provisional_date
    FROM filler f
    UNION ALL
    SELECT
      1,
      b.bill_rank * 100000 + b.rn,
      b.booking_id,
      b.artist_type,
      b.artist_profile_id,
      b.band_id,
      b.npc_artist_id,
      b.artist_name,
      b.billing_position,
      b.set_minutes,
      b.provisional_date
    FROM booked b
  ), numbered AS (
    SELECT *, row_number() OVER (ORDER BY grp, ord) slot_no
    FROM items
  ), stage_rows AS (
    SELECT * FROM stages
  )
  SELECT jsonb_build_object(
    'stages', coalesce(
      (
        SELECT jsonb_agg(
          jsonb_build_object(
            'id', s.id,
            'name', s.name,
            'sortOrder', s.sort_order,
            'capacity', s.capacity
          )
          ORDER BY s.sort_order
        )
        FROM stage_rows s
      ),
      '[]'::jsonb
    ),
    'items', coalesce(
      (
        SELECT jsonb_agg(
          jsonb_build_object(
            'id', gen_random_uuid(),
            'sourceBookingId', n.booking_id,
            'artistType', n.artist_type,
            'artistProfileId', n.artist_profile_id,
            'bandId', n.band_id,
            'npcArtistId', n.npc_artist_id,
            'artistName', n.artist_name,
            'billingPosition', n.billing_position,
            'setMinutes', n.set_minutes,
            'festivalDate', e.starts_on + (((n.slot_no - 1) / slots_per_day)::int),
            'stageId', (
              SELECT s.id
              FROM stage_rows s
              ORDER BY s.sort_order
              OFFSET ((n.slot_no - 1) % greatest(1, stage_count))
              LIMIT 1
            ),
            'slotIndex', n.slot_no
          )
          ORDER BY n.slot_no
        )
        FROM numbered n
      ),
      '[]'::jsonb
    )
  ) INTO generated;

  generated := generated || jsonb_build_object('timezone',zone);
  config := jsonb_build_object(
    'rulesVersion', 'canonical-live-day-v1',
    'timezone', zone,
    'startsOn', e.starts_on,
    'endsOn', e.ends_on,
    'editionId', e.id,
    'sitePlanId', site.id,
    'ticketPlanId', ticket.id,
    'programmeId', programme.id,
    'generatedSchedule', generated,
    'readiness', readiness,
    'seed', seed,
    'slotsPerDay', slots_per_day,
    'licensedActsPerDay', licensed_acts_per_day
  );
  config_digest := encode(digest(config::text, 'sha256'), 'hex');

  INSERT INTO public.festival_edition_runtimes(
    edition_id, festival_company_id, state, simulated_time, gate_status,
    last_action, idempotency_key, schedule_source, generated_schedule,
    expected_attendance, site_capacity, runtime_seed, licence_snapshot,
    started_by_profile_id, started_at
  ) VALUES (
    e.id, e.festival_company_id, 'gates_open', observed_at, 'open',
    'open_gates', p_idempotency_key::text, 'simplified_generated', generated,
    expected, site.usable_capacity, seed, coalesce(readiness->'activeLicence','{}'),
    actor, observed_at
  ) RETURNING * INTO r;

  INSERT INTO public.festival_runtime_configuration_versions(
    runtime_id, edition_id, rules_version, configuration, configuration_digest
  ) VALUES (r.id, e.id, 'canonical-live-day-v1', config, config_digest);

  INSERT INTO public.festival_runtime_action_audit(
    runtime_id, actor_profile_id, action, previous_state, new_state, metadata
  ) VALUES (r.id, actor, 'open_gates', NULL, r.state,
    jsonb_build_object('idempotencyKey',p_idempotency_key));

  UPDATE public.festival_editions_v2 SET status='live', version=version+1,
    locked_at=coalesce(locked_at,observed_at), updated_at=observed_at
  WHERE id=e.id;
  RETURN public._festival_runtime_projection(r.id, actor);
END;
$function$;

