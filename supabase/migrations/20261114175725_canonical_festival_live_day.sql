CREATE FUNCTION public.advance_canonical_festival_live_day(
 p_runtime_id uuid, p_expected_version integer, p_request_id uuid,
 p_action text, p_arrivals integer DEFAULT 0, p_departures integer DEFAULT 0,
 p_stage_counts jsonb DEFAULT '{}'::jsonb, p_other_zones integer DEFAULT 0
) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO pg_catalog, extensions
AS $live$
DECLARE
 actor uuid := public._caller_profile_id();
 r public.festival_edition_runtimes%ROWTYPE;
 e public.festival_editions_v2%ROWTYPE;
 cfg public.festival_runtime_configuration_versions%ROWTYPE;
 observed_at timestamptz;
 local_day date;
 previous_state text;
 next_state text;
 request_hash text;
 prior_hash text;
 admitted_total bigint;
 departed_total bigint;
 onsite bigint;
 allocated bigint := 0;
 stage record;
 stage_capacity integer;
 payload jsonb;
 evidence_hash text;
BEGIN
 IF auth.uid() IS NULL OR actor IS NULL THEN RAISE EXCEPTION 'festival_runtime_forbidden'; END IF;

 SELECT * INTO r FROM public.festival_edition_runtimes WHERE id=p_runtime_id;
 IF NOT FOUND OR NOT coalesce(public._festival_edition_runtime_authorised(
   r.festival_company_id,r.edition_id,actor),false)
 THEN RAISE EXCEPTION 'festival_runtime_forbidden'; END IF;

 -- Same lock ordering as start/simulation, followed by the stage-action row lock.
 PERFORM pg_advisory_xact_lock(hashtextextended(r.edition_id::text,0));
 SELECT * INTO e FROM public.festival_editions_v2 WHERE id=r.edition_id FOR UPDATE;
 SELECT * INTO r FROM public.festival_edition_runtimes WHERE id=p_runtime_id AND edition_id=e.id FOR UPDATE;
 IF NOT FOUND OR NOT coalesce(public._festival_edition_runtime_authorised(
   r.festival_company_id,r.edition_id,actor),false)
   OR EXISTS (SELECT 1 FROM public.festival_edition_runtimes newer
              WHERE newer.edition_id=r.edition_id AND (newer.created_at,newer.id)>(r.created_at,r.id))
 THEN RAISE EXCEPTION 'festival_runtime_forbidden'; END IF;

 SELECT * INTO cfg FROM public.festival_runtime_configuration_versions
 WHERE runtime_id=r.id AND edition_id=e.id AND rules_version='canonical-live-day-v1';
 IF NOT FOUND THEN RAISE EXCEPTION 'festival_live_runtime_required'; END IF;
 IF p_request_id IS NULL OR p_action IS NULL OR p_arrivals IS NULL OR p_departures IS NULL
    OR p_other_zones IS NULL OR least(p_arrivals,p_departures,p_other_zones)<0
    OR jsonb_typeof(p_stage_counts) IS DISTINCT FROM 'object'
 THEN RAISE EXCEPTION 'festival_live_request_invalid'; END IF;

 request_hash := encode(digest(jsonb_build_array(
   p_expected_version,p_action,p_arrivals,p_departures,p_stage_counts,p_other_zones
 )::text,'sha256'),'hex');
 SELECT receipt.request_hash INTO prior_hash FROM private.festival_live_day_receipts receipt
 WHERE runtime_id=r.id AND request_id=p_request_id;
 IF FOUND THEN
   IF prior_hash<>request_hash THEN RAISE EXCEPTION 'festival_live_request_conflict'; END IF;
   RETURN public._festival_runtime_projection(r.id,actor);
 END IF;
 IF r.version IS DISTINCT FROM p_expected_version OR e.status<>'live' THEN
   RAISE EXCEPTION 'festival_runtime_stale';
 END IF;

 observed_at := clock_timestamp();
 local_day := (observed_at AT TIME ZONE (cfg.configuration->>'timezone'))::date;
 previous_state := r.state;
 next_state := CASE
   WHEN p_action='start_live' AND r.state='gates_open' THEN 'live'
   WHEN p_action='pause' AND r.state='live' THEN 'paused'
   WHEN p_action='resume' AND r.state='paused' THEN 'live'
   WHEN p_action='close' AND r.state IN ('gates_open','live','paused') THEN 'closing'
   WHEN p_action='finish' AND r.state='closing' THEN 'completed'
   WHEN p_action='cancel' AND r.state IN ('gates_open','live','paused','closing') THEN 'aborted'
   WHEN p_action='tick' AND r.state IN ('gates_open','live','paused','closing') THEN r.state
 END;
 IF next_state IS NULL THEN RAISE EXCEPTION 'festival_live_transition_invalid'; END IF;
 IF p_action IN ('start_live','resume') AND local_day NOT BETWEEN
   (cfg.configuration->>'startsOn')::date AND (cfg.configuration->>'endsOn')::date
 THEN RAISE EXCEPTION 'festival_live_outside_edition'; END IF;

 admitted_total := r.admitted_attendance::bigint + p_arrivals;
 departed_total := r.departed_attendance::bigint + p_departures;
 onsite := admitted_total - departed_total;

 IF p_action='tick' THEN
   IF onsite NOT BETWEEN 0 AND r.site_capacity OR admitted_total>r.expected_attendance
      OR p_departures>r.site_attendance::bigint+p_arrivals
      OR (p_arrivals>0 AND (
        r.state NOT IN ('gates_open','live') OR local_day NOT BETWEEN
          (cfg.configuration->>'startsOn')::date AND (cfg.configuration->>'endsOn')::date
      ))
   THEN RAISE EXCEPTION 'festival_live_attendance_invalid'; END IF;

   IF r.state IN ('gates_open','live') AND local_day BETWEEN
      (cfg.configuration->>'startsOn')::date AND (cfg.configuration->>'endsOn')::date
   THEN
     IF (SELECT count(*) FROM jsonb_object_keys(p_stage_counts)) <>
        jsonb_array_length(cfg.configuration #> '{generatedSchedule,stages}')
     THEN RAISE EXCEPTION 'festival_live_stage_counts_incomplete'; END IF;
     FOR stage IN SELECT * FROM jsonb_each(p_stage_counts) LOOP
       SELECT (item->>'capacity')::integer INTO stage_capacity
       FROM jsonb_array_elements(cfg.configuration #> '{generatedSchedule,stages}') item
       WHERE item->>'id'=stage.key;
       IF stage_capacity IS NULL OR jsonb_typeof(stage.value)<>'number'
          OR stage.value::text !~ '^[0-9]{1,8}$'
          OR stage.value::text::integer>stage_capacity
       THEN RAISE EXCEPTION 'festival_live_stage_capacity_invalid'; END IF;
       allocated := allocated + stage.value::text::integer;
     END LOOP;
   ELSIF p_stage_counts<>'{}'::jsonb THEN
     RAISE EXCEPTION 'festival_live_stage_counts_unavailable';
   END IF;
   IF allocated + p_other_zones <> onsite THEN
     RAISE EXCEPTION 'festival_live_attendance_not_conserved';
   END IF;
 ELSIF p_arrivals<>0 OR p_departures<>0 OR p_stage_counts<>'{}'::jsonb OR p_other_zones<>0 THEN
   RAISE EXCEPTION 'festival_live_counts_require_tick';
 END IF;

 IF p_action IN ('close','finish') AND local_day < (cfg.configuration->>'endsOn')::date THEN
   RAISE EXCEPTION 'festival_live_final_day_required';
 END IF;
 IF p_action IN ('close','finish') AND EXISTS (
   SELECT 1 FROM (
     SELECT DISTINCT ON (schedule_item_id) event_status
     FROM private.festival_edition_stage_events ev WHERE ev.runtime_id=r.id AND ev.festival_date=local_day
     ORDER BY schedule_item_id,ev.observed_at DESC,ev.recorded_at DESC
   ) latest WHERE event_status IN ('starting','live')
 ) THEN RAISE EXCEPTION 'festival_live_stage_still_running'; END IF;
 IF p_action IN ('finish','cancel') AND onsite<>0 THEN
   RAISE EXCEPTION 'festival_live_site_not_clear';
 END IF;

 UPDATE public.festival_edition_runtimes SET
   state=next_state, version=version+1, simulated_time=observed_at, last_action=p_action,
   gate_status=CASE WHEN next_state IN ('gates_open','live') THEN 'open' ELSE 'closed' END,
   admitted=admitted_total, departed=departed_total, admitted_attendance=admitted_total,
   departed_attendance=departed_total, site_attendance=onsite,
   completed_at=CASE WHEN next_state='completed' THEN observed_at END
 WHERE id=r.id RETURNING * INTO r;

 IF p_action='tick' THEN
   payload := jsonb_build_object(
     'requestId',p_request_id,'runtimeVersion',r.version,'festivalDate',local_day,
     'observedAt',observed_at,'arrivals',p_arrivals,'departures',p_departures,
     'onsite',onsite,'otherZones',p_other_zones,'stageCounts',p_stage_counts
   );
   INSERT INTO public.festival_runtime_evidence(runtime_id,evidence_type,evidence,evidence_digest)
   VALUES (r.id,'live_day_tick',payload,encode(digest(payload::text,'sha256'),'hex'));

   FOR stage IN SELECT * FROM jsonb_each(p_stage_counts) LOOP
     payload := jsonb_build_object(
       'stageId',stage.key,'audienceTotal',stage.value,'observedAt',observed_at,
       'festivalDate',local_day,'idempotencyKey',p_request_id::text||':'||stage.key,
       'allocationSource','canonical_runtime_stage_allocation'
     );
     INSERT INTO public.festival_runtime_evidence(runtime_id,evidence_type,evidence,evidence_digest)
     VALUES (r.id,'stage_audience_allocation',payload,encode(digest(payload::text,'sha256'),'hex'));
   END LOOP;
 END IF;

 IF p_action='finish' THEN
   SELECT encode(digest(coalesce(jsonb_agg(evidence_digest ORDER BY id),'[]')::text,'sha256'),'hex')
   INTO evidence_hash FROM public.festival_runtime_evidence WHERE runtime_id=r.id;
   payload := jsonb_build_object(
     'configurationDigest',cfg.configuration_digest,'observationsDigest',evidence_hash,
     'runtimeVersion',r.version,'admittedAttendance',admitted_total,'departedAttendance',departed_total
   );
   evidence_hash := encode(digest(payload::text,'sha256'),'hex');
   INSERT INTO public.festival_runtime_evidence(runtime_id,evidence_type,evidence,evidence_digest)
   VALUES (r.id,'completion',payload,evidence_hash);

   INSERT INTO public.festival_runtime_completion_digests(
     runtime_id,edition_id,rules_version,runtime_digest,evidence_digest,completed_at
   ) VALUES (r.id,e.id,cfg.rules_version,encode(digest(
     jsonb_build_array(r.id,e.id,evidence_hash)::text,'sha256'),'hex'),evidence_hash,observed_at);
 END IF;

 IF next_state IN ('completed','aborted') THEN
   UPDATE public.festival_editions_v2 SET
     status=CASE WHEN next_state='completed' THEN 'completed' ELSE 'cancelled' END,
     completed_at=r.completed_at, version=version+1, updated_at=observed_at
   WHERE id=e.id;
 END IF;

 INSERT INTO public.festival_runtime_action_audit(
   runtime_id,actor_profile_id,action,previous_state,new_state,metadata
 ) VALUES (r.id,actor,p_action,previous_state,next_state,
   jsonb_build_object('requestId',p_request_id,'runtimeVersion',r.version));

 INSERT INTO private.festival_live_day_receipts(runtime_id,request_id,request_hash)
 VALUES (r.id,p_request_id,request_hash);
 RETURN public._festival_runtime_projection(r.id,actor);
END;
$live$;

REVOKE ALL ON FUNCTION public.advance_canonical_festival_live_day(uuid,integer,uuid,text,integer,integer,jsonb,integer)
 FROM PUBLIC, anon, authenticated, service_role;
GRANT EXECUTE ON FUNCTION public.advance_canonical_festival_live_day(uuid,integer,uuid,text,integer,integer,jsonb,integer)
 TO authenticated;


