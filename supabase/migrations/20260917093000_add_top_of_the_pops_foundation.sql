-- Top of the Pops phase 1 foundation.
-- Server-authoritative fortnightly television event driven by immutable UK chart snapshots.

CREATE TABLE IF NOT EXISTS public.totp_episodes (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  episode_date date NOT NULL UNIQUE,
  episode_number bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  status text NOT NULL DEFAULT 'scheduled' CHECK (status IN ('scheduled', 'inviting', 'locked', 'recording', 'broadcast', 'completed', 'cancelled')),
  chart_snapshot_date date NOT NULL,
  city_id uuid NOT NULL REFERENCES public.cities(id),
  check_in_at timestamptz NOT NULL,
  broadcast_at timestamptz NOT NULL,
  max_performances integer NOT NULL DEFAULT 10 CHECK (max_performances BETWEEN 1 AND 20),
  presenter_key text NOT NULL DEFAULT 'alex_rayne',
  broadcast_profile text NOT NULL DEFAULT 'totp_classic',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.totp_candidates (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  episode_id uuid NOT NULL REFERENCES public.totp_episodes(id) ON DELETE CASCADE,
  band_id uuid NOT NULL REFERENCES public.bands(id) ON DELETE CASCADE,
  song_id uuid NOT NULL REFERENCES public.songs(id) ON DELETE CASCADE,
  chart_rank integer NOT NULL CHECK (chart_rank BETWEEN 1 AND 40),
  qualifying_chart text NOT NULL CHECK (qualifying_chart IN ('streaming', 'digital_sales', 'both')),
  chart_snapshot_date date NOT NULL,
  selection_bucket text NOT NULL CHECK (selection_bucket IN ('top10', '11_20', '21_40')),
  selected boolean NOT NULL DEFAULT false,
  ineligible_reason text,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (episode_id, band_id),
  UNIQUE (episode_id, song_id)
);

CREATE TABLE IF NOT EXISTS public.totp_invitations (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  episode_id uuid NOT NULL REFERENCES public.totp_episodes(id) ON DELETE CASCADE,
  candidate_id uuid NOT NULL REFERENCES public.totp_candidates(id) ON DELETE CASCADE,
  band_id uuid NOT NULL REFERENCES public.bands(id) ON DELETE CASCADE,
  song_id uuid NOT NULL REFERENCES public.songs(id) ON DELETE CASCADE,
  qualifying_rank integer NOT NULL CHECK (qualifying_rank BETWEEN 1 AND 40),
  status text NOT NULL DEFAULT 'invited' CHECK (status IN ('invited', 'accepted', 'declined', 'expired', 'checked_in', 'performed', 'missed')),
  invited_at timestamptz NOT NULL DEFAULT now(),
  response_deadline timestamptz NOT NULL,
  responded_at timestamptz,
  checked_in_at timestamptz,
  missed_reason text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (episode_id, band_id),
  UNIQUE (episode_id, song_id)
);

CREATE TABLE IF NOT EXISTS public.totp_performances (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  episode_id uuid NOT NULL REFERENCES public.totp_episodes(id) ON DELETE CASCADE,
  invitation_id uuid NOT NULL UNIQUE REFERENCES public.totp_invitations(id) ON DELETE CASCADE,
  band_id uuid NOT NULL REFERENCES public.bands(id) ON DELETE CASCADE,
  song_id uuid NOT NULL REFERENCES public.songs(id) ON DELETE CASCADE,
  running_order integer CHECK (running_order BETWEEN 1 AND 20),
  stage_key text NOT NULL DEFAULT 'main_stage',
  camera_profile text NOT NULL DEFAULT 'totp_classic',
  presenter_intro text,
  performance_score integer CHECK (performance_score BETWEEN 0 AND 100),
  fame_awarded integer NOT NULL DEFAULT 0 CHECK (fame_awarded >= 0),
  completed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (episode_id, running_order),
  UNIQUE (episode_id, band_id)
);

CREATE INDEX IF NOT EXISTS totp_candidates_episode_rank_idx ON public.totp_candidates (episode_id, chart_rank);
CREATE INDEX IF NOT EXISTS totp_invitations_band_idx ON public.totp_invitations (band_id, episode_id);
CREATE INDEX IF NOT EXISTS totp_performances_band_idx ON public.totp_performances (band_id, episode_id);

ALTER TABLE public.totp_episodes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.totp_candidates ENABLE ROW LEVEL SECURITY;
