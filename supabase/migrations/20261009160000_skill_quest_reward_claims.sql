-- Phase 2 reward claims: durable, server-owned bookkeeping only.
-- No XP mutation occurs until a reviewed reward processor is introduced.
create table if not exists public.skill_quest_reward_claims (
  id uuid primary key default gen_random_uuid(),
  profile_id uuid not null references public.profiles(id) on delete cascade,
  quest_id text not null check (length(quest_id) between 1 and 100),
  reward_kind text not null check (reward_kind in ('xp')),
  reward_amount integer not null check (reward_amount > 0),
  status text not null default 'pending' check (status in ('pending','processing','granted','retry_required')),
  xp_ledger_id uuid references public.experience_ledger(id) on delete restrict,
  created_at timestamptz not null default now(),
  granted_at timestamptz,
  constraint skill_quest_reward_claims_unique unique (profile_id, quest_id, reward_kind),
  constraint skill_quest_reward_claims_granted_evidence check (
    status <> 'granted' or (xp_ledger_id is not null and granted_at is not null)
  )
);
create index if not exists skill_quest_reward_claims_pending_idx
  on public.skill_quest_reward_claims(status, created_at)
  where status in ('pending','retry_required');
alter table public.skill_quest_reward_claims enable row level security;
revoke all on public.skill_quest_reward_claims from public, anon, authenticated;
grant select on public.skill_quest_reward_claims to authenticated;
drop policy if exists skill_quest_reward_claims_owner_read on public.skill_quest_reward_claims;
create policy skill_quest_reward_claims_owner_read
on public.skill_quest_reward_claims for select to authenticated
using (exists (
  select 1 from public.profiles p
  where p.id = skill_quest_reward_claims.profile_id and p.user_id = (select auth.uid())
));

-- Deliberately no client RPC, auto-claim trigger, or configured rewards.
-- Claims must be generated by a server-only verified quest completion processor.
-- XP must be posted atomically with status='granted' and xp_ledger_id.
-- xp_ledger_id is the legacy API field name; its FK targets the live experience_ledger.
